def pick_return_probability(adp, next_pick_overall, adp_noise_std=6.0):
    if next_pick_overall is None:
        return 1.0
    return float(norm.sf((next_pick_overall - adp) / adp_noise_std))

def _reseed_pairs(seed_to_team):
    seeds_sorted = sorted(seed_to_team.keys())
    n = len(seeds_sorted)
    if n % 2 != 0:
        raise ValueError(f"_reseed_pairs needs an even number of teams, got {n}: {seeds_sorted}")
    pairs = []
    for i in range(n // 2):
        hi, lo = seeds_sorted[i], seeds_sorted[n - 1 - i]
        pairs.append((seed_to_team[hi], seed_to_team[lo], hi, lo))
    return pairs

