def dispatch_command(tracker, raw, weekly_games_df=None, time_budget=None):
    """Runs one loop command (same grammar as the original CLI loop) and
    returns everything it printed, as a single string, instead of writing
    straight to stdout. Shared by the CLI (run_draft_loop) and the web app
    (app.py) so both stay behind one code path.

    time_budget: optional seconds of Monte Carlo time for top3 / check (the
    web app passes the long-mode budget); None = TOP3_TIME_BUDGET_SEC.
    """
    wg = weekly_games_df if weekly_games_df is not None else tracker.weekly_games_df
    raw = (raw or "").strip()
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        if not raw:
            pass
        else:
            cmd, *rest = raw.split(maxsplit=1)
            arg = rest[0].strip() if rest else ""
            low = cmd.lower()
            if low == "help":
                print(_LOOP_HELP)
            elif low == "top3":
                target = int(arg) if arg.strip().isdigit() else tracker.pick_order[tracker.overall - 1]
                top3, note = recommend_top3(tracker, weekly_games_df=wg, team=target, time_budget=time_budget)
                print_top3_table(top3, note, tracker=tracker, team=target)
            elif low in ("check", "checkplayers"):
                cmd_check(tracker, arg, wg, time_budget=time_budget)
            elif low == "catrank":
                cmd_catrank(tracker, wg)
            elif low in ("h2hstand", "h2h"):
                cmd_h2hstand(tracker, wg)
            elif low in _SOURCE_COMMANDS:
                kind, source_label = _SOURCE_COMMANDS[low]
                if kind == "catrank":
                    cmd_source_catrank(tracker, source_label, wg)
                elif kind == "playoffbracket":
                    cmd_source_playoffbracket(tracker, source_label, wg)
                else:
                    cmd_source_h2hstand(tracker, source_label, wg)
            elif low in ("playoffbracket", "bracket"):
                cmd_playoffbracket(tracker, wg)
            elif low in ("endofseason",):
                cmd_endofseason(tracker, wg)
            elif low == "snake":
                set_draft_mode(tracker, "snake")
            elif low == "3rr":
                set_draft_mode(tracker, "3rr")
            elif low == "status":
                tracker.print_status()
            elif low == "undo":
                tracker.undo_last_pick()
                print(f"-> undone; now on pick #{tracker.overall}")
            else:
                _log_pick(tracker, raw)
    return buf.getvalue()


def run_draft_loop(tracker, weekly_games_df=None):
    """Original terminal loop, now a thin wrapper around dispatch_command."""
    wg = weekly_games_df if weekly_games_df is not None else tracker.weekly_games_df
    print("=== Fantasy Basketball Draft Assistant (v31) ===")
    print(f"Auto-recommend teams: {sorted(tracker.auto_recommend_teams) or 'none'}")
    print(_LOOP_HELP)
    print(dispatch_command(tracker, "", wg), end="")
    tracker._maybe_auto_recommend()  # kept for parity; dispatch_command("") does nothing itself
    while True:
        try:
            raw = input("\n> ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nExiting draft loop.")
            break
        if not raw:
            continue
        if raw.lower() in ("q", "quit", "exit"):
            print("Exiting draft loop.")
            break
        print(dispatch_command(tracker, raw, wg), end="")


