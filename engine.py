def catrank_table(tracker, weekly_games_df=None, rcol_prefix=None):
    """Season-total category totals per team, weighted by each drafted
    player's real number of games across the regular-season schedule (every
    week referenced by SCORING_PERIOD_TO_WEEKS -- weeks 1-19, NOT the 2
    trailing non-fantasy weeks some schedule exports tack on the end, and NOT
    the playoff weeks). FG%/FT% are computed from summed makes/attempts
    (season-long volume), not an average-of-averages.

    rcol_prefix: pass a specific prefix (e.g. from _resolve_named_source_prefix)
    to score against a single projection source instead of the default blended
    ensemble. Leave None for the normal tracker default.

    Returns (values_df, ranks_df), both indexed by team number.
    """
    wg = weekly_games_df if weekly_games_df is not None else tracker.weekly_games_df
    if wg is None:
        raise ValueError("catrank_table needs a weekly_games_df (pass one, or "
                          "build the tracker with weekly_games_df=...).")
    rcol_prefix = rcol_prefix or tracker.rcol_prefix or _resolve_rcol_prefix(tracker.pool, None)
    reg_weeks = sorted({w for weeks in SCORING_PERIOD_TO_WEEKS.values() for w in weeks})
    reg_weeks = [w for w in reg_weeks if w in wg.index]

    rows = []
    for t in range(1, tracker.teams + 1):
        roster = tracker.rosters[t]
        raw = {}
        for wk in reg_weeks:
            raw = _add_raw(raw, _team_week_raw_totals(tracker.pool, roster, wk, wg, rcol_prefix))
        totals = _finalize_week_totals(raw)
        row = {"team": t, "players_drafted": len(roster)}
        row.update({c: (0.0 if pd.isna(totals.get(c, 0.0)) else totals.get(c, 0.0)) for c in CAT_COLS})
        rows.append(row)
    values_df = pd.DataFrame(rows).set_index("team")

    ranks_df = pd.DataFrame(index=values_df.index)
    for c in CAT_COLS:
        ascending = (c == "TO")  # fewer turnovers is better; everything else higher is better
        ranks_df[c] = values_df[c].rank(ascending=ascending, method="min").astype(int)
    ranks_df.insert(0, "players_drafted", values_df["players_drafted"])
    return values_df, ranks_df


def alliance_loss_table(tracker, weekly_games_df=None, rcol_prefix=None):
    """Every regular-season scoring-period matchup (REGULAR_SEASON_SCHEDULE)
    involving an alliance team that the alliance team is currently projected
    to LOSE. One row per such matchup."""
    wg = weekly_games_df if weekly_games_df is not None else tracker.weekly_games_df
    if wg is None:
        raise ValueError("alliance_loss_table needs a weekly_games_df.")
    rcol_prefix = rcol_prefix or tracker.rcol_prefix or _resolve_rcol_prefix(tracker.pool, None)
    alliance = set(tracker.alliance_allies or ()) | {tracker.my_slot}
    cache = {}
    rows = []
    for sp in sorted(REGULAR_SEASON_SCHEDULE.keys()):
        weeks = SCORING_PERIOD_TO_WEEKS[sp]
        for a, b in REGULAR_SEASON_SCHEDULE[sp]:
            if a not in alliance and b not in alliance:
                continue
            result = simulate_multiweek_matchup(tracker.pool, tracker.rosters[a], tracker.rosters[b],
                                                 wg, weeks=weeks, rcol_prefix=rcol_prefix, cache=cache)
            loser = winner = None
            if result["winner"] == "A" and b in alliance:
                loser, winner, la, lb = b, a, result["cats_b"], result["cats_a"]
            elif result["winner"] == "B" and a in alliance:
                loser, winner, la, lb = a, b, result["cats_a"], result["cats_b"]
            if loser is not None:
                rows.append({
                    "scoring_period": sp, "weeks": "/".join(str(w) for w in weeks),
                    "alliance_team": loser, "loses_to": winner,
                    "cats_won": la, "cats_lost": lb,
                })
    cols = ["scoring_period", "weeks", "alliance_team", "loses_to", "cats_won", "cats_lost"]
    return pd.DataFrame(rows, columns=cols)


