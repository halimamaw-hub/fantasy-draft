def attach_consensus_rankings(pool, extra_rank_csv=None):
    """Attach a draft-market consensus board -- CSV-only, no PDFs required.

    v31 change: the old version required uploading Yahoo/NBA.com PDF ranking
    exports on draft day and parsed them with pypdf. That dependency is gone.
    Fantrax ADP (the live-draft anchor -- what the room is actually drafting
    off of) is now the sole default consensus source, which is what the old
    version already weighted most heavily (0.55) anyway.

    Optionally, `extra_rank_csv` can point at a plain CSV with "Player" and
    "Rank" columns (any other ranking export you want to blend in) -- no PDF
    library needed for that either. If omitted, Consensus_Rank == Fantrax ADP.
    """
    pool = pool.copy()
    pool["Fantrax_ADP"] = pd.to_numeric(pool.get("ADP", np.nan), errors="coerce")
    norm_names = pool["Player"].map(_norm_name)

    extra = _v14_9cat_csv_rankings(extra_rank_csv) if extra_rank_csv else {}
    pool["Extra_Rank"] = norm_names.map(extra)

    if extra:
        ranks = pd.concat([
            pool["Fantrax_ADP"].rename("Fantrax"),
            pool["Extra_Rank"].rename("Extra"),
        ], axis=1)
        weights = np.array([0.7, 0.3])
        values = ranks.to_numpy(dtype=float)
        valid = np.isfinite(values)
        numer = np.nansum(values * weights, axis=1)
        denom = valid @ weights
        consensus = np.divide(numer, denom, out=np.full(len(pool), np.nan), where=denom > 0)
        pool["Consensus_Rank"] = consensus
        pool["Consensus_Source_Count"] = valid.sum(axis=1)
    else:
        pool["Consensus_Rank"] = pool["Fantrax_ADP"]
        pool["Consensus_Source_Count"] = pool["Fantrax_ADP"].notna().astype(int)
    pool["Consensus_Diff_Fantrax"] = pool["Fantrax_ADP"] - pool["Consensus_Rank"]
    print(
        f"[rankings] Fantrax={pool['Fantrax_ADP'].notna().sum()} | "
        f"Extra={len(extra)}"
    )
    return pool


def _v14_9cat_csv_rankings(csv_path):
    """Read a supplied CSV ranking file (must contain Player + Rank columns)."""
    if not csv_path or not _V12Path(csv_path).exists():
        return {}
    try:
        df = pd.read_csv(csv_path)
    except Exception as exc:
        print(f"[rankings] could not read ranking CSV {csv_path}: {exc}")
        return {}
    if "Player" not in df.columns or "Rank" not in df.columns:
        print(f"[rankings] {csv_path} must contain Player and Rank columns.")
        return {}
    rank = pd.to_numeric(df["Rank"], errors="coerce")
    out = {}
    for name, r in zip(df["Player"], rank):
        if pd.notna(r) and int(r) > 0:
            out[_norm_name(name)] = int(r)
    return out

class V12OpponentModel:
    """Fast opponent model shared by live predictions and draft simulations."""
    PERSONALITIES = {
        1: ("fantrax", 0.70, 0.12),
        2: ("yahoo",   0.66, 0.15),
        3: ("yahoo",   0.68, 0.14),
        4: ("bpa",     0.78, 0.08),
        5: ("need",    0.58, 0.22),
        8: ("risk",    0.52, 0.28),
        10:("bpa",     0.75, 0.10),
    }

    def __init__(self, tracker):
        self.tracker = tracker
        self.pool = tracker.pool.reset_index(drop=True)
        self.names = self.pool["Player"].to_numpy()
        self.name_to_i = {p: i for i, p in enumerate(self.names)}
        self.adp = pd.to_numeric(self.pool.get("Fantrax_ADP", self.pool["ADP"]), errors="coerce").fillna(999).to_numpy(float)
        self.consensus = pd.to_numeric(self.pool.get("Consensus_Rank", self.pool["ADP"]), errors="coerce").fillna(999).to_numpy(float)
        # BUG FIX (v31): these used to fillna(999) -- a flat constant for every
        # player once the Yahoo/NBA.com PDF columns were removed, which would
        # have flattened the "yahoo" personality's board into near-random
        # order (Personalities 2 and 3). Fall back to the real Consensus_Rank
        # (== Fantrax ADP with no extra source) instead, so those opponents
        # still draft off a sane market board.
        self.yahoo = pd.to_numeric(self.pool.get("Yahoo_Rank", pd.Series(np.nan, index=self.pool.index)), errors="coerce").fillna(pd.Series(self.consensus)).to_numpy(float)
        self.nba9 = pd.to_numeric(self.pool.get("NBA_9Cat_Rank", pd.Series(np.nan, index=self.pool.index)), errors="coerce").fillna(pd.Series(self.consensus)).to_numpy(float)
        self.fantrax = self.adp.copy()
        self.zmat = np.nan_to_num(self.pool[[f"{tracker.zcol_prefix}{c}" for c in CAT_COLS]].to_numpy(float), nan=0.0)
        self.pos = {p: self.pool["Position"].str.contains(p).to_numpy(float) for p in ("G", "F", "C")}

    def _source_rank(self, personality):
        if personality == "yahoo": return self.yahoo
        if personality == "fantrax": return self.fantrax
        return self.consensus

    def pick(self, team, available_names, overall, rng, roster_names=None):
        idx = np.array([self.name_to_i[p] for p in available_names if p in self.name_to_i], dtype=int)
        if len(idx) == 0:
            return None

        rnd = int(((overall - 1) // self.tracker.teams) + 1)
        personality, market_w, need_w = self.PERSONALITIES.get(team, ("bpa", 0.75, 0.10))
        source_rank = self._source_rank(personality)
        window = V12_DEFAULT_OPP_WINDOW.get(min(rnd, 4), 20)

        # KEY FIX: early rounds use a narrow consensus window. This prevents a
        # category-fit player ranked 30th from jumping a consensus 1st-rounder.
        order = idx[np.argsort(source_rank[idx])]
        window_idx = order[:min(window, len(order))]

        # Need is deliberately weak early and increases later.
        need_scale = 0.05 if rnd <= 3 else (0.14 if rnd <= 6 else 0.24)
        if personality == "need": need_scale *= 1.20
        if personality == "risk": need_scale *= 0.85

        roster_names = roster_names or []
        if roster_names:
            roster_idx = [self.name_to_i[p] for p in roster_names if p in self.name_to_i]
            totals = self.zmat[roster_idx].sum(axis=0) if roster_idx else np.zeros(len(CAT_COLS))
        else:
            totals = np.zeros(len(CAT_COLS))
        weak_order = np.argsort(totals)[:3]
        need_score = self.zmat[window_idx][:, weak_order].sum(axis=1)
        need_score = (need_score - np.mean(need_score)) / (np.std(need_score) + 1e-9)

        # Positional need matters more after a roster starts to take shape.
        pos_need = np.zeros(len(window_idx))
        if rnd >= 3:
            for pos, minimum in (("G", 2), ("F", 2), ("C", 1)):
                have = sum(1 for p in roster_names if self.pool.loc[self.name_to_i.get(p, -1), "Position"] if False)
            # Fast position counts without pandas indexing.
            roster_i = [self.name_to_i[p] for p in roster_names if p in self.name_to_i]
            for pos, minimum in (("G", 2), ("F", 2), ("C", 1)):
                have = int(self.pos[pos][roster_i].sum()) if roster_i else 0
                if have < minimum:
                    pos_need += self.pos[pos][window_idx]
        else:
            pos_need[:] = 0.0

        # Early rounds need to stay anchored to the public market board.
        # 0.35-spot-equivalent noise is enough to create small realistic reaches
        # without allowing a 30th-ranked player to jump the 1st-round tier.
        noise = rng.normal(0, 0.35 if rnd <= 3 else (0.75 if rnd <= 6 else 1.25), size=len(window_idx))
        source_score = -(source_rank[window_idx] / 10.0)
        consensus_score = -(self.consensus[window_idx] / 10.0)
        score = market_w * source_score + (1.0 - market_w) * consensus_score
        score += need_scale * need_score + 0.08 * pos_need + 0.05 * self.zmat[window_idx].sum(axis=1) + noise

        chosen_i = int(window_idx[int(np.argmax(score))])
        return self.names[chosen_i]

def get_v12_opponent_model(tracker):
    cached = getattr(tracker, "_v12_opponent_model", None)
    if cached is None or getattr(cached, "pool", None) is None or len(cached.pool) != len(tracker.pool):
        cached = V12OpponentModel(tracker)
        tracker._v12_opponent_model = cached
    return cached

def v12_project_remaining_rosters(tracker, extra_locked=None, max_steps=None, seed=0):
    """Full remaining-draft projection with one evolving state per team."""
    rosters = {t: list(r) for t, r in tracker.rosters.items()}
    extra_locked = extra_locked or {}
    for t, players in extra_locked.items():
        for p in players:
            if p not in rosters[t]:
                rosters[t].append(p)

    taken = {p for r in rosters.values() for p in r}
    start = tracker.overall
    end = len(tracker.pick_order)
    if max_steps is not None:
        end = min(end, start + max_steps - 1)
    rng = np.random.default_rng(seed)
    model = get_v12_opponent_model(tracker)
    predicted = []

    for overall in range(start, end + 1):
        team = tracker.pick_order[overall - 1]
        if len(rosters[team]) >= tracker.rounds:
            continue
        avail = [p for p in tracker.pool["Player"].tolist() if p not in taken]
        if not avail:
            break
        pname = model.pick(team, avail, overall, rng, rosters[team])
        if pname is None:
            continue
        rosters[team].append(pname)
        taken.add(pname)
        predicted.append((overall, team, pname))
    return rosters, predicted

def _v12_team_strength(tracker, roster_names):
    if not roster_names:
        return np.zeros(len(CAT_COLS))
    model = get_v12_opponent_model(tracker)
    inds = [model.name_to_i[p] for p in roster_names if p in model.name_to_i]
    if not inds:
        return np.zeros(len(CAT_COLS))
    return model.zmat[inds].sum(axis=0)

def _v12_proxy_seed_order(tracker, rosters):
    vals = []
    for t in range(1, tracker.teams + 1):
        z = _v12_team_strength(tracker, rosters[t])
        # Equal-ish emphasis across cats. TO is already sign-inverted in z data.
        strength = float(z.sum())
        vals.append((t, strength))
    vals.sort(key=lambda x: x[1], reverse=True)
    return {seed: team for seed, (team, _) in enumerate(vals, start=1)}

def _v12_proxy_playoff_winner(tracker, rosters, team_a, team_b, rng):
    za = _v12_team_strength(tracker, rosters[team_a])
    zb = _v12_team_strength(tracker, rosters[team_b])
    # Category-by-category win count + a small stochastic upset term.
    a_cats = int(np.sum(za > zb))
    b_cats = int(np.sum(zb > za))
    margin = (a_cats - b_cats) + 0.18 * float((za - zb).sum())
    noise = rng.normal(0, 0.85)
    return team_a if margin + noise >= 0 else team_b

def _v12_proxy_playoffs(tracker, rosters, rng):
    """Fast stochastic playoff proxy matching the league's reseeding shape.

    Six byes (seeds 1-6); Round 1 is 8v9 and 7v10. Each later round reseeds
    highest-vs-lowest among survivors. Semifinal losers play the 3rd-place game.
    """
    seed_to_team = _v12_proxy_seed_order(tracker, rosters)
    bye_n = getattr(tracker, "bye_seeds", DEFAULT_BYE_SEEDS)

    def play_pair(seed_map, pairs=None):
        pairs = pairs or []
        out = {}
        logs = []
        ss = sorted(seed_map)
        for i in range(len(ss) // 2):
            hi, lo = ss[i], ss[-1 - i]
            a, b = seed_map[hi], seed_map[lo]
            winner = _v12_proxy_playoff_winner(tracker, rosters, a, b, rng)
            win_seed = hi if winner == a else lo
            lose_seed = lo if winner == a else hi
            out[win_seed] = winner
            logs.append((winner, seed_map[lose_seed], hi, lo))
        return out, logs

    # Round 1: only non-bye seeds 7-10 play, i.e. 8v9 and 7v10.
    first = {s: seed_to_team[s] for s in sorted(seed_to_team) if s > bye_n}
    r1, _ = play_pair(first)
    survivors = {s: seed_to_team[s] for s in sorted(seed_to_team) if s <= bye_n}
    survivors.update(r1)

    # Round 2 and Round 3 reseed after each round.
    r2, _ = play_pair(survivors)
    r3, sf_logs = play_pair(r2)

    final_seeds = sorted(r3)
    a_seed, b_seed = final_seeds[0], final_seeds[-1]
    a_team, b_team = r3[a_seed], r3[b_seed]
    champion = _v12_proxy_playoff_winner(tracker, rosters, a_team, b_team, rng)
    runner = b_team if champion == a_team else a_team

    # sf_logs has two entries, each (winner, loser, winner_seed, loser_seed).
    semifinal_losers = [entry[1] for entry in sf_logs]
    if len(semifinal_losers) == 2:
        third = _v12_proxy_playoff_winner(tracker, rosters, semifinal_losers[0], semifinal_losers[1], rng)
    else:
        # Defensive fallback; should never be reached for the 10-team bracket.
        third = next(t for t in rosters if t not in {champion, runner})
    return champion, runner, third

def _v12_fast_draft_rollout(tracker, forced_team, forced_player, seed):
    rng = np.random.default_rng(seed)
    model = get_v12_opponent_model(tracker)
    rosters = {t: list(r) for t, r in tracker.rosters.items()}
    taken = {p for r in rosters.values() for p in r}
    if forced_player in taken:
        return None
    rosters[forced_team].append(forced_player)
    taken.add(forced_player)

    for overall in range(tracker.overall + 1, len(tracker.pick_order) + 1):
        team = tracker.pick_order[overall - 1]
        if len(rosters[team]) >= tracker.rounds:
            continue
        avail = [p for p in model.names.tolist() if p not in taken]
        if not avail:
            break
        if team in V12_ALLIANCE:
            # Alliance teams also behave realistically in the rollout. We don't
            # recursively call recommend_top3; this is the major speed fix.
            idx = np.array([model.name_to_i[p] for p in avail], dtype=int)
            round_num = ((overall - 1) // tracker.teams) + 1
            # Market-first early; roster-fit later.
            consensus = model.consensus[idx]
            score = -consensus / 10.0
            if round_num >= 4:
                zi = model.zmat[idx]
                score += 0.18 * zi.sum(axis=1)
            score += rng.normal(0, 1.75, size=len(idx))
            pname = model.names[idx[int(np.argmax(score))]]
        else:
            pname = model.pick(team, avail, overall, rng, rosters[team])
        if pname is None:
            break
        rosters[team].append(pname)
        taken.add(pname)

    champ, runner, third = _v12_proxy_playoffs(tracker, rosters, rng)
    alliance = set(V12_ALLIANCE)
    sweep = {champ, runner, third} == alliance
    # Also record top-3 regular-season proxy to separate draft strength from
    # playoff variance.
    seedmap = _v12_proxy_seed_order(tracker, rosters)
    season_top3 = set(list(seedmap.values())[:3]) == alliance
    return {"champion": champ, "runner_up": runner, "third": third,
            "sweep": sweep, "season_sweep": season_top3, "rosters": rosters}

def v12_fast_candidate_mc(tracker, team, candidate, min_trials=24, max_trials=96,
                          batch=12, target_sweep=V12_DEFAULT_TARGET_SWEEP,
                          conf_margin=V12_DEFAULT_CONF_MARGIN, seed=0, deadline=None):
    """Sequential MC: start small, add batches only when candidates remain close.

    deadline: optional time.monotonic() timestamp. Once at least
    _V15_MC_MIN_TRIAL_FLOOR trials are banked, hitting the deadline stops the
    loop immediately -- same early-stop logic as before, just with a hard
    wall-clock ceiling added on top so one slow candidate can't blow the
    live top3 recommendation's time budget. Accuracy on a fast machine is
    unaffected: the deadline only bites when it would otherwise be missed.
    """
    trials = 0
    sweeps = seasons = champs = podium_2plus = 0
    top3_share_sum = 0.0
    losses = {a: 0 for a in V12_ALLIANCE}
    while trials < max_trials:
        this_batch = min(batch, max_trials - trials)
        for j in range(this_batch):
            res = _v12_fast_draft_rollout(tracker, team, candidate, seed + trials + j + 1)
            if res is None:
                continue
            trials += 1
            sweep_set={res["champion"],res["runner_up"],res["third"]} & set(V12_ALLIANCE)
            podium_2plus += int(len(sweep_set) >= 2)
            sweeps += int(res["sweep"])
            seasons += int(res["season_sweep"])
            champs += int(res["champion"] == team)
            top3_share_sum += len(sweep_set) / 3.0
            if (deadline is not None and trials >= _V15_MC_MIN_TRIAL_FLOOR
                    and time.monotonic() >= deadline):
                break
        if (deadline is not None and trials >= _V15_MC_MIN_TRIAL_FLOOR
                and time.monotonic() >= deadline):
            break
        if trials < min_trials:
            continue
        p = sweeps / trials if trials else 0.0
        se = math.sqrt(max(p * (1 - p), 1e-9) / trials)
        # Stop early when the estimated sweep rate is either comfortably good
        # enough or clearly not competitive, OR when uncertainty is small.
        if p >= target_sweep and (p - 1.96 * se) >= max(0.50, target_sweep - 0.10):
            break
        if p < 0.20 and (p + 1.96 * se) < 0.35:
            break
        if 1.96 * se < 0.045:
            break
    p = sweeps / trials if trials else 0.0
    return {
        "mc_sweep_prob": p,
        "mc_podium_2plus_prob": podium_2plus / trials if trials else 0.0,
        "mc_season_sweep_prob": seasons / trials if trials else 0.0,
        "mc_team_champ_prob": champs / trials if trials else 0.0,
        "mc_alliance_top3_share": top3_share_sum / trials if trials else 0.0,
        "mc_trials": trials,
        "mc_ci_low": max(0.0, p - 1.96 * math.sqrt(max(p * (1 - p), 1e-9) / max(trials, 1))),
        "mc_ci_high": min(1.0, p + 1.96 * math.sqrt(max(p * (1 - p), 1e-9) / max(trials, 1))),
    }

def _v12_candidate_base_table(tracker, team, only_players=None):
    """Generate a compact candidate table before MC. This is intentionally cheap.

    only_players: optional list of player names. When given, the table holds
    exactly those (still-available) players -- same value/swing/availability
    columns and the same pre_mc_score formula -- instead of the usual
    shortlist of the ~8 best candidates. Used by the `check` command.
    """
    round_num = tracker.current_round
    max_punts = max_punts_for_round(round_num, 2)
    roster = list(tracker.rosters[team])
    taken = set(tracker._drafted_to_team)
    avail = tracker.pool[~tracker.pool["Player"].isin(taken)].copy()
    if avail.empty:
        return pd.DataFrame(), []

    cat_weights = tracker.category_weights(swing_bonus=2.0, team=team)
    prefix = tracker.zcol_prefix
    active = [c for c in CAT_COLS]
    avail["value_z"] = avail[[f"{prefix}{c}" for c in active]].sum(axis=1)
    avail["swing_alignment"] = 0.0
    for c in active:
        avail["swing_alignment"] += avail[f"{prefix}{c}"] * (cat_weights[c] - 1.0)
    avail["consensus_value"] = -pd.to_numeric(avail.get("Consensus_Rank", avail["ADP"]), errors="coerce")

    next_pick = next_own_pick_overall(tracker, after=tracker.overall, team=team)
    avail["return_prob_next_pick"] = [
        pick_return_probability(float(a), next_pick, 7.0) for a in pd.to_numeric(avail["ADP"], errors="coerce")
    ]
    avail["sniped_before_next_pick_pct"] = 100.0 * (1.0 - avail["return_prob_next_pick"])

    if only_players is not None:
        base = avail[avail["Player"].isin(list(only_players))].copy()
        if base.empty:
            return pd.DataFrame(), []
        base["was_milp_pick"] = False
        alpha = min(1.0, max(0.0, (round_num - 1) / 5.0))
        base["pre_mc_score"] = ((1 - alpha) * base["value_z"] + 0.30 * base["swing_alignment"]
                                 + alpha * base["consensus_value"] / 10.0
                                 + 0.25 * (1.0 - base["return_prob_next_pick"]))
        order = {p: i for i, p in enumerate(only_players)}
        base = base.assign(_ord=base["Player"].map(order)).sort_values("_ord").drop(columns="_ord")
        return base.reset_index(drop=True), []

    # Candidate pool: consensus top, Fantrax ADP top, z-value top, and MILP.
    top_cons = avail.sort_values("Consensus_Rank").head(8) if "Consensus_Rank" in avail else avail.sort_values("ADP").head(8)
    top_adp = avail.sort_values("ADP").head(8)
    top_value = avail.sort_values("value_z", ascending=False).head(8)
    try:
        chosen, punted, _ = solve_roster(avail, current_roster_names=roster,
                                         roster_size=tracker.rounds, max_punts=max_punts,
                                         zcol_prefix=prefix, cat_weights=cat_weights)
        milp = chosen[~chosen["Player"].isin(roster)].sort_values("Consensus_Rank" if "Consensus_Rank" in chosen else "ADP").head(8)
    except Exception:
        punted, milp = [], avail.head(0)
    cands = list(dict.fromkeys(
        top_cons["Player"].tolist() + top_adp["Player"].tolist() + top_value["Player"].tolist() + milp["Player"].tolist()
    ))
    base = avail[avail["Player"].isin(cands)].copy()
    base["was_milp_pick"] = base["Player"].isin(set(milp["Player"]))
    # Cheap pre-MC score: early rounds strongly protect market value; later
    # rounds allow roster need to matter.
    alpha = min(1.0, max(0.0, (round_num - 1) / 5.0))
    base["pre_mc_score"] = ((1 - alpha) * base["value_z"] + 0.30 * base["swing_alignment"]
                             + alpha * base["consensus_value"] / 10.0
                             + 0.25 * (1.0 - base["return_prob_next_pick"]))
    base = base.sort_values("pre_mc_score", ascending=False).head(8)
    return base.reset_index(drop=True), punted

