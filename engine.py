def simulate_playoff_bracket(pool, rosters, seed_to_team, weekly_games_df,
                              playoff_weeks=DEFAULT_PLAYOFF_WEEKS, bye_seeds=DEFAULT_BYE_SEEDS,
                              rcol_prefix=None, cache=None):
    rcol_prefix = _resolve_rcol_prefix(pool, rcol_prefix)
    if len(playoff_weeks) != 4:
        raise ValueError(f"simulate_playoff_bracket expects exactly 4 playoff weeks "
                          f"(round1, round2, round3, final), got {playoff_weeks}")
    expected_seeds = set(range(1, len(seed_to_team) + 1))
    if set(seed_to_team.keys()) != expected_seeds:
        raise ValueError(
            f"simulate_playoff_bracket: seed_to_team keys must be exactly "
            f"1..{len(seed_to_team)} (one per team), got {sorted(seed_to_team.keys())}."
        )
    if len(set(seed_to_team.values())) != len(seed_to_team):
        raise ValueError(
            f"simulate_playoff_bracket: seed_to_team has a duplicate team slot -- "
            f"each team must appear at exactly one seed. Got: {seed_to_team}"
        )
    w1, w2, w3, wf = playoff_weeks

    def play(team_a, team_b, seed_a, seed_b, week):
        sim = simulate_weekly_matchup(pool, rosters[team_a], rosters[team_b], weekly_games_df,
                                       playoff_weeks=(week,), rcol_prefix=rcol_prefix, cache=cache)
        info = sim["weekly"][week]
        if info["week_winner"] == "A":
            winner, loser, winner_seed, loser_seed = team_a, team_b, seed_a, seed_b
        elif info["week_winner"] == "B":
            winner, loser, winner_seed, loser_seed = team_b, team_a, seed_b, seed_a
        else:
            if seed_a < seed_b:
                winner, loser, winner_seed, loser_seed = team_a, team_b, seed_a, seed_b
            else:
                winner, loser, winner_seed, loser_seed = team_b, team_a, seed_b, seed_a
        return {
            "team_a": team_a, "team_b": team_b, "seed_a": seed_a, "seed_b": seed_b,
            "cats_a": info["cats_won_a"], "cats_b": info["cats_won_b"],
            "tied_on_categories": info["week_winner"] == "Tie",
            "winner": winner, "winner_seed": winner_seed,
            "loser": loser, "loser_seed": loser_seed,
        }

    all_seeds = sorted(seed_to_team.keys())
    bye_seed_list = all_seeds[:bye_seeds]
    playin_seeds = all_seeds[bye_seeds:]
    if len(playin_seeds) % 2 != 0:
        raise ValueError(f"{len(playin_seeds)} non-bye seeds is odd -- can't pair "
                          f"them for Round 1. Check `bye_seeds` against your bracket.")

    round1_log = []
    survivors_r2 = {s: seed_to_team[s] for s in bye_seed_list}
    for team_hi, team_lo, seed_hi, seed_lo in _reseed_pairs({s: seed_to_team[s] for s in playin_seeds}):
        result = play(team_hi, team_lo, seed_hi, seed_lo, w1)
        survivors_r2[result["winner_seed"]] = result["winner"]
        round1_log.append(result)

    round2_log = []
    survivors_r3 = {}
    for team_hi, team_lo, seed_hi, seed_lo in _reseed_pairs(survivors_r2):
        result = play(team_hi, team_lo, seed_hi, seed_lo, w2)
        survivors_r3[result["winner_seed"]] = result["winner"]
        round2_log.append(result)

    round3_log = []
    finalists = {}
    third_place_field = []
    for team_hi, team_lo, seed_hi, seed_lo in _reseed_pairs(survivors_r3):
        result = play(team_hi, team_lo, seed_hi, seed_lo, w3)
        finalists[result["winner_seed"]] = result["winner"]
        third_place_field.append((result["loser"], result["loser_seed"]))
        round3_log.append(result)

    fseeds = sorted(finalists.keys())
    champ_result = play(finalists[fseeds[0]], finalists[fseeds[1]], fseeds[0], fseeds[1], wf)

    (tp_team_a, tp_seed_a), (tp_team_b, tp_seed_b) = third_place_field
    third_result = play(tp_team_a, tp_team_b, tp_seed_a, tp_seed_b, wf)

    return {
        "seed_to_team": dict(seed_to_team),
        "bye_seeds": list(bye_seed_list),
        "round1": round1_log, "round2": round2_log, "round3": round3_log,
        "final": champ_result, "third_place": third_result,
        "champion": champ_result["winner"], "runner_up": champ_result["loser"],
        "third_place_winner": third_result["winner"], "fourth_place": third_result["loser"],
    }

def summarize_bracket(bracket):
    def fmt_match(m):
        tie_note = " [tied on categories -- higher seed advanced]" if m["tied_on_categories"] else ""
        return (f"Seed {m['seed_a']} (Team {m['team_a']}) vs Seed {m['seed_b']} "
                f"(Team {m['team_b']}) -> Team {m['winner']} wins "
                f"{m['cats_a']}-{m['cats_b']}{tie_note}")

    lines = [f"Byes into Round 2: seeds {bracket['bye_seeds']}", "", "Round 1:"]
    lines += ["  " + fmt_match(m) for m in bracket["round1"]]
    lines += ["", "Round 2:"]
    lines += ["  " + fmt_match(m) for m in bracket["round2"]]
    lines += ["", "Round 3 (Semifinal):"]
    lines += ["  " + fmt_match(m) for m in bracket["round3"]]
    lines += ["", "Final Round -- Championship:", "  " + fmt_match(bracket["final"])]
    lines += ["", "Final Round -- 3rd Place Game:", "  " + fmt_match(bracket["third_place"])]
    lines += ["", f"CHAMPION: Team {bracket['champion']}  |  Runner-up: Team {bracket['runner_up']}  |  "
                   f"3rd Place: Team {bracket['third_place_winner']}  |  4th Place: Team {bracket['fourth_place']}"]
    return "\n".join(lines)

def _trial_rosters_with_candidate(tracker, team, cand, orig_roster, projected_rosters):
    """
    FIX #22 -- this is what killed the alliance signal outright.

    recommend_top3 used to build each candidate's trial league as
    `dict(projected_rosters)` followed by `rosters_for_trial[team] =
    orig_roster + [cand]`. `projected_rosters` holds a FULL 14-man projection
    for every team, so that line replaced the on-the-clock team's 14-man
    projection with its 4-or-5-man PARTIAL roster, then simulated a bracket of
    5 players against nine 14-man opponents. Measured at pick 41 of a mock
    draft: trial roster sizes came out {team 9: 5, every other team: 14}. Team 9
    lost every bracket match for every candidate, alliance_goal_delta returned
    0.0 across the board, and the entire alliance weight (0.10-0.15 of the
    score) collapsed to no signal. The baseline it was differenced against used
    team 9's full 14-man projection, so the comparison was not even
    like-for-like.

    Two further defects fixed here: the candidate was left duplicated on
    whichever team the projection had already assigned him to (verified True in
    the same run), and the projection's own pick for the on-the-clock team was
    never displaced. The trial now holds every roster at its projected size,
    forces `cand` onto `team` in place of that team's least valuable projected
    addition, and removes `cand` from any other team the projection gave him to.
    """
    if projected_rosters is None:
        rosters = {t: list(r) for t, r in tracker.rosters.items()}
        rosters[team] = list(orig_roster) + [cand]
        return rosters

    rosters = {t: list(r) for t, r in projected_rosters.items()}

    # A candidate cannot be on two teams at once. Whoever the projection gave
    # him to gets backfilled with the best undrafted player, so that team is not
    # silently left a man short -- otherwise every candidate quietly handicapped
    # a different opponent and the bracket moved for the wrong reason. Verified:
    # before the backfill, trial roster sizes came out [13, 14] mid-draft.
    for t, r in list(rosters.items()):
        if t != team and cand in r:
            rosters[t] = [p for p in r if p != cand]
            used = {p for rr in rosters.values() for p in rr} | {cand}
            spare = tracker.pool[~tracker.pool["Player"].isin(used)]
            if not spare.empty:
                rosters[t].append(spare.sort_values("ADP").iloc[0]["Player"])

    own = rosters.get(team, list(orig_roster))
    if cand in own:
        return rosters  # the projection already had us taking him

    locked = set(orig_roster)
    projected_adds = [p for p in own if p not in locked]
    if projected_adds:
        lut = tracker._zvec_lookup()
        zero = np.zeros(len(CAT_COLS))
        weakest = min(projected_adds, key=lambda p: float(lut.get(p, zero).sum()))
        own = [p for p in own if p != weakest]
    rosters[team] = own + [cand]
    return rosters

