def _v15_team_cat_matrix(tracker, rosters):
    pool = tracker.pool
    prefix = tracker.zcol_prefix
    lut = {p:i for i,p in enumerate(pool['Player'])}
    z = np.nan_to_num(pool[[f'{prefix}{c}' for c in CAT_COLS]].to_numpy(float), nan=0.0)
    out = {}
    for t, r in rosters.items():
        inds=[lut[p] for p in r if p in lut]
        out[t] = z[inds].sum(axis=0) if inds else np.zeros(len(CAT_COLS))
    return out

def _v15_category_complementarity(tracker, rosters, allies=None):
    """v32: reward each ally being broadly strong across categories, not
    reward the three allies having *different* category profiles.

    The old version explicitly rewarded "dispersion" and "profile_div" --
    i.e. it paid a bonus for the three alliance rosters looking as different
    from each other as possible, which is precisely a cover-your-teammate's-
    punt strategy (team A stacks blocks/boards, team B stacks assists/steals,
    etc., and each relies on an ally to carry the categories it ignores).
    That is the opposite of what the alliance wants now: each team should be
    independently competitive in as many categories as possible.

    This version scores "dominance" instead of "divergence":
      * avg_strength  -- mean z-score of the three allies across all 9
                          categories (raw category strength, unchanged sign).
      * floor_strength -- the WEAKEST ally's z-score in each category,
                          averaged. This is the key change: it is high only
                          when *every* ally is solid in *every* category, and
                          it is low if any single ally is quietly punting a
                          category and hoping the other two cover it.
    No divergence/dispersion term remains, so there is no longer any reward
    for the three rosters looking different from one another.
    """
    allies = tuple(allies or V15_ALLIANCE)
    cat_totals = _v15_team_cat_matrix(tracker, rosters)
    league = np.array([cat_totals[t] for t in range(1, tracker.teams+1)], dtype=float)
    mu = league.mean(axis=0)
    sd = league.std(axis=0) + 1e-9
    az = np.array([(cat_totals[t]-mu)/sd for t in allies], dtype=float)
    if az.size == 0:
        return 0.0
    avg_strength = float(np.mean(np.clip(az, -2.0, 2.0)))
    weakest_per_cat = az.min(axis=0)
    floor_strength = float(np.mean(np.clip(weakest_per_cat, -2.0, 2.0)))
    return float(avg_strength + 0.6*floor_strength)

def _v15_min_strength_score(tracker, rosters, allies=None):
    """Weak-link protection: penalize any alliance team below the league floor."""
    allies = tuple(allies or V15_ALLIANCE)
    cat_totals = _v15_team_cat_matrix(tracker, rosters)
    strengths = {t: float(v.sum()) for t,v in cat_totals.items()}
    league_vals = np.array(list(strengths.values()), dtype=float)
    if len(league_vals) == 0:
        return 0.0
    floor = float(np.quantile(league_vals, V15_MIN_STRENGTH_QUANTILE))
    weakest = min((strengths.get(t, -1e9) for t in allies), default=-1e9)
    # Positive when weakest ally clears the minimum threshold; negative below it.
    scale = float(np.std(league_vals) + 1e-9)
    return float((weakest - floor) / scale)

def _v15_project_next_alliance_turns(tracker, team, candidate, n_turns=2):
    """Project strictly *after* the current pick, with candidate locked in.

    This avoids the subtle double-pick bug that would occur if the generic
    remaining-roster projector were allowed to simulate the current overall pick
    again after candidate had already been inserted.
    """
    rosters={t:list(r) for t,r in tracker.rosters.items()}
    if candidate and candidate not in rosters[team]:
        rosters[team].append(candidate)
    taken={p for r in rosters.values() for p in r}
    model=get_v12_opponent_model(tracker)
    rng=np.random.default_rng(tracker.overall + team + 1515)
    seq=[]
    start=tracker.overall + 1
    for overall in range(start, len(tracker.pick_order)+1):
        on_clock=tracker.pick_order[overall-1]
        if len(rosters[on_clock])>=tracker.rounds:
            continue
        avail=[p for p in tracker.pool['Player'].tolist() if p not in taken]
        if not avail:
            break
        pname=model.pick(on_clock,avail,overall,rng,rosters[on_clock])
        if pname is None:
            continue
        rosters[on_clock].append(pname); taken.add(pname); seq.append((overall,on_clock,pname))
    current_alliance = set(V15_ALLIANCE)
    future_alliance_picks=[]
    for overall, t, player in seq:
        if overall <= tracker.overall:
            continue
        if t in current_alliance:
            future_alliance_picks.append((overall,t,player))
            if len(future_alliance_picks) >= max(1, n_turns):
                break
    # Identify the scarce consensus players likely to remain at each next alliance turn.
    rank = pd.to_numeric(tracker.pool.get('Consensus_Rank', tracker.pool['ADP']), errors='coerce').fillna(999)
    rankmap = dict(zip(tracker.pool['Player'], rank))
    scarce_bonus = 0.0
    for overall, t, player in future_alliance_picks:
        r = float(rankmap.get(player, 999))
        scarce_bonus += 1.0 / max(r, 1.0)
    # Strong candidate bonus if its projected disappearance would otherwise leave
    # a large gap between top remaining and the projected ally pick.
    taken_now=set(tracker._drafted_to_team)
    if candidate in taken_now:
        taken_now.remove(candidate)
    available=[p for p in tracker.pool['Player'] if p not in taken_now and p != candidate]
    top_remaining=sorted(available, key=lambda p: float(rankmap.get(p,999)))[:8]
    top_remaining_ranks=[float(rankmap.get(p,999)) for p in top_remaining]
    scarcity_gap=0.0
    if future_alliance_picks and top_remaining_ranks:
        # Higher score means the candidate resolves a scarce tier before it dries up.
        target=float(rankmap.get(candidate,999))
        next_best=min(top_remaining_ranks)
        scarcity_gap=(next_best-target)/max(target,1.0)
    return float(scarce_bonus + scarcity_gap), future_alliance_picks

def _v15_playoff_path_score(tracker, rosters, weekly_games_df=None, seed_to_team=None):
    """Fast schedule-aware playoff-path proxy.

    The live recommender must not run the full bracket for every candidate.  We
    therefore use the existing playoff-schedule-adjusted category projections
    (`zpo_ens_*`) to estimate each alliance team's category margin against the
    strongest likely non-alliance playoff opponents.  The exact 4-round bracket
    remains the authoritative final validation in the draft simulator.
    """
    prefix_cols=[f'zpo_ens_{c}' if f'zpo_ens_{c}' in tracker.pool.columns else f'{tracker.zcol_prefix}{c}' for c in CAT_COLS]
    lut={p:i for i,p in enumerate(tracker.pool['Player'])}
    zpo=np.nan_to_num(tracker.pool[prefix_cols].to_numpy(float),nan=0.0)
    strengths={}; cats={}
    for t,r in rosters.items():
        inds=[lut[p] for p in r if p in lut]
        cats[t]=zpo[inds].sum(axis=0) if inds else np.zeros(len(CAT_COLS))
        strengths[t]=float(cats[t].sum())
    ordered=sorted(strengths,key=strengths.get,reverse=True)
    allies=set(V15_ALLIANCE)
    non_allies=[t for t in ordered if t not in allies]
    if not non_allies:
        return 0.0, None
    # Use the top four projected non-alliance teams as likely playoff threats.
    threats=non_allies[:4]
    margins=[]
    for a in allies:
        za=cats[a]
        for opp in threats:
            zb=cats[opp]
            margins.append(float(np.mean(np.sign(za-zb)) + 0.10*np.mean(za-zb)))
    path=float(np.mean(margins)) if margins else 0.0
    # Reward projected bye status softly because byes remove one upset path.
    rank={t:i+1 for i,t in enumerate(ordered)}
    bye_bonus=float(np.mean([1.0 if rank.get(a,99)<=tracker.bye_seeds else 0.0 for a in allies]))
    return path + 0.25*bye_bonus, {'projected_seed':rank,'threats':threats}

def _v15_portfolio_metrics(tracker, rosters, late_round=False, include_lookahead=False):
    # Start from the v13 metrics so all previously implemented terms remain active.
    base = _v13_portfolio_metrics(tracker, rosters, late_round=late_round)
    comp = _v15_category_complementarity(tracker, rosters)
    min_strength = _v15_min_strength_score(tracker, rosters)
    path_score, path_bracket = _v15_playoff_path_score(tracker, rosters)
    lookahead_val = 0.0
    if include_lookahead:
        for overall,t,p in _v15_project_next_alliance_turns(tracker, tracker.my_slot, '', n_turns=V15_LAST_LOOKAHEAD_ALLY_TURNS)[1]:
            if t in set(V15_ALLIANCE):
                lookahead_val += float(1.0/(1.0+overall))
    base.update({
        'complementarity': comp,
        'min_strength': min_strength,
        'playoff_path': path_score,
        'playoff_path_bracket': path_bracket,
        'last_player_lookahead': lookahead_val,
    })
    return base

def _v15_portfolio_score(metrics, baseline_metrics=None, weights=None):
    w={**V15_DEFAULT_WEIGHTS, **(weights or {})}
    score=(w['sweep']*float(metrics['top3_count']==3)
           +w['two_plus_top3']*float(metrics['two_plus_top3'])
           +w['top3_seed_count']*(float(metrics['top3_count'])/3.0)
           +w['bye_seed_count']*(float(metrics['bye_count'])/3.0)
           +w['balance']*metrics['balance']
           +w['category_floor']*metrics['category_floor']
           +w['collision_avoidance']*metrics['collision_avoidance']
           +w['portfolio_value']*metrics['portfolio_value']/10.0
           +w['playoff_path']*metrics['playoff_path']
           +w['complementarity']*metrics['complementarity']
           +w['min_strength']*metrics['min_strength']
           +w['last_player_lookahead']*metrics['last_player_lookahead'])
    if baseline_metrics is not None:
        for key,coef in [('category_floor',0.05),('balance',0.04),('collision_avoidance',0.04),
                         ('complementarity',0.04),('min_strength',0.05),('playoff_path',0.05),
                         ('last_player_lookahead',0.04)]:
            score += coef*float(metrics.get(key,0)-baseline_metrics.get(key,0))
    return float(score)

def _v32_final_score_weights(round_num):
    """v32: round-based blend between raw player value (pre_mc_score, which
    is anchored to consensus/ADP/market value) and the alliance-portfolio
    score (seeding, dominance, floor -- everything about *where the three
    allies land*).

    Early picks should be close to best-player-available so the team is
    simply strong; portfolio/seeding considerations earn more say only as
    the roster fills in and marginal player-value differences shrink. This
    caps how far any single pick can reach ahead of ADP for portfolio-only
    reasons -- portfolio weight never exceeds 0.55, so raw value always has
    real influence, even very late.
    """
    portfolio_w = min(0.55, 0.20 + 0.03 * max(0, round_num - 1))
    return portfolio_w, 1.0 - portfolio_w


def _v15_simulation_batch_top3(tracker, team):
    """Cheap portfolio policy for hundreds of complete-draft simulations.

    It preserves the same objective terms but avoids recursively projecting the
    entire remaining draft for every candidate. Exact regular-season and playoff
    outcomes are still evaluated after the simulated draft is complete.
    """
    taken=set(tracker._drafted_to_team)
    base,_=_v12_candidate_base_table(tracker,team)
    if base.empty:return base
    cands=base.sort_values('pre_mc_score',ascending=False).head(5)['Player'].tolist()
    current={t:list(r) for t,r in tracker.rosters.items()}
    baseline=_v15_portfolio_metrics(tracker,current,late_round=tracker.current_round>=V13_LATE_ROUNDS)
    rows=[]
    for cand in cands:
        trial={t:list(r) for t,r in current.items()}
        trial[team]=trial.get(team,[])+[cand]
        m=_v15_portfolio_metrics(tracker,trial,late_round=tracker.current_round>=V13_LATE_ROUNDS,include_lookahead=False)
        r=base.loc[base.Player==cand].iloc[0].to_dict()
        portfolio_score=_v15_portfolio_score(m,baseline)
        podium_proxy=float(m['top3_count']>=2)
        sweep_proxy=float(m['top3_count']==3)
        dual_proxy=(V15_DUAL_TARGET_WEIGHT*podium_proxy+V15_SWEEP_FLOOR_WEIGHT*sweep_proxy
                    -V15_TARGET_PENALTY*((V15_PODIUM_TARGET-podium_proxy if podium_proxy<V15_PODIUM_TARGET else 0.0)**2
                                         +1.35*(V15_SWEEP_FLOOR-sweep_proxy if sweep_proxy<V15_SWEEP_FLOOR else 0.0)**2))
        r.update({'v13_portfolio_score':portfolio_score,
                  'v15_podium_proxy':podium_proxy,
                  'v15_sweep_proxy':sweep_proxy,
                  'v15_dual_target_proxy':dual_proxy,
                  'v13_alliance_seeds':m['ally_seeds'],
                  'v13_alliance_seed_map':m['ally_seed_map'],
                  'v13_top3_count':m['top3_count'],
                  'v13_bye_count':m['bye_count'],
                  'v13_balance':m['balance'],
                  'v13_category_floor':m['category_floor'],
                  'v13_collision_avoidance':m['collision_avoidance'],
                  'v15_playoff_path':m['playoff_path'],
                  'v15_complementarity':m['complementarity'],
                  'v15_min_strength':m['min_strength'],
                  'v15_last_player_lookahead':0.0})
        pw,vw=_v32_final_score_weights(tracker.current_round)
        r['v13_final_score']=(pw*(0.62*r['v15_dual_target_proxy']+0.38*r['v13_portfolio_score'])
                              +vw*r.get('pre_mc_score',0))
        rows.append(r)
    return pd.DataFrame(rows).sort_values(['v13_final_score','pre_mc_score'],ascending=False).reset_index(drop=True).head(3)

def v15_batch_top3(tracker, team, deadline=None, players=None):
    """players: optional list of names to score instead of the auto shortlist
    (the `check` command). Every listed player is scored -- the deadline never
    skips one -- and all of them are returned, not just three."""
    if players is None and getattr(tracker, '_simulation_mode', False):
        return _v15_simulation_batch_top3(tracker, team)
    taken=set(tracker._drafted_to_team)
    avail=tracker.pool[~tracker.pool['Player'].isin(taken)].copy()
    if avail.empty: return avail
    base,_=_v12_candidate_base_table(tracker,team,only_players=players)
    if base.empty: return base
    # Keep a broader shortlist so late scarcity and portfolio effects can rescue
    # players that are just outside the pure BPA top tier.
    if players is not None:
        shortlist=base['Player'].tolist()
    else:
        shortlist=base.sort_values('pre_mc_score',ascending=False).head(8)['Player'].tolist()
    projected,_=v12_project_remaining_rosters(tracker,seed=tracker.overall+team+15)
    baseline=_v15_portfolio_metrics(tracker,projected,late_round=tracker.current_round>=V13_LATE_ROUNDS,include_lookahead=False)
    rows=[]
    for i,cand in enumerate(shortlist):
        # Once the top 3 (by pure pre-MC value) are scored, later candidates
        # in the shortlist are marginal portfolio-fit rescues -- fine to skip
        # under time pressure rather than let a slow CPU blow the deadline.
        if players is None and deadline is not None and i >= 3 and time.monotonic() >= deadline:
            break
        trial={t:list(r) for t,r in projected.items()}
        trial=_trial_rosters_with_candidate(tracker,team,cand,tracker.rosters[team],trial)
        m=_v15_portfolio_metrics(tracker,trial,late_round=tracker.current_round>=V13_LATE_ROUNDS,include_lookahead=False)
        look,_future=_v15_project_next_alliance_turns(tracker,team,cand,V15_LAST_LOOKAHEAD_ALLY_TURNS)
        m['last_player_lookahead'] += look
        score=_v15_portfolio_score(m,baseline)
        r=base.loc[base.Player==cand].iloc[0].to_dict()
        r.update({'v13_portfolio_score':score,
                  'v13_alliance_seeds':m['ally_seeds'],
                  'v13_alliance_seed_map':m['ally_seed_map'],
                  'v13_top3_count':m['top3_count'],
                  'v13_bye_count':m['bye_count'],
                  'v13_balance':m['balance'],
                  'v13_category_floor':m['category_floor'],
                  'v13_collision_avoidance':m['collision_avoidance'],
                  'v15_playoff_path':m['playoff_path'],
                  'v15_complementarity':m['complementarity'],
                  'v15_min_strength':m['min_strength'],
                  'v15_last_player_lookahead':m['last_player_lookahead']})
        # v32: anchor hard to real player value/consensus (best-player-
        # available) in early rounds, and only let the alliance-seeding
        # portfolio score gain real weight once the roster shape is mostly
        # set. This is what curbs big reaches ahead of ADP/consensus (e.g.
        # a player being taken 30+ spots early purely for portfolio fit) --
        # the old weighting (0.68 portfolio / 0.32 value from round 1) let
        # portfolio fit dominate a value-based draft from the very first pick.
        pw,vw=_v32_final_score_weights(tracker.current_round)
        if tracker.current_round>=V13_LATE_ROUNDS:
            r['v13_final_score']=(pw*(0.55*score+0.25*m['category_floor']+0.20*m['min_strength'])
                                  +vw*r.get('pre_mc_score',0))
        else:
            r['v13_final_score']=pw*score+vw*r.get('pre_mc_score',0)
        rows.append(r)
    out=pd.DataFrame(rows)
    return out.sort_values(['v13_final_score','pre_mc_score'],ascending=False).reset_index(drop=True).head(len(shortlist) if players is not None else 3)

def _v15_adaptive_mc(tracker, team, candidate_rows, seed=0, deadline=None, budget=None, max_names=3):
    """Fast sequential MC with separate podium and sweep targets.

    podium_2plus_prob = probability that >=2 alliance teams occupy the 3
    podium slots; sweep_prob = probability all 3 alliance teams do so.
    The stopping rule uses the dual objective instead of optimizing sweep alone.

    deadline: optional time.monotonic() timestamp for the whole call (first
    pass over up to 3 candidates, plus the possible top-2 refinement pass
    below). Whatever time remains is split evenly across whichever candidates
    still need to run, so no single candidate can eat the entire budget and
    starve the others -- each just gets fewer trials if time is short.
    """
    if deadline is None:
        deadline = time.monotonic() + (budget or TOP3_TIME_BUDGET_SEC)
    names=candidate_rows['Player'].tolist()[:max_names]
    results={}
    n_names=len(names)
    for j,p in enumerate(names):
        remaining=max(0.0, deadline - time.monotonic())
        # +1 reserves a slice for the potential refinement pass below.
        slots_left=max(1, (n_names - j) + 1)
        cand_deadline=time.monotonic() + remaining / slots_left
        results[p]=v12_fast_candidate_mc(
            tracker,team,p,min_trials=V15_LIVE_MIN,max_trials=V15_LIVE_MAX,
            batch=V15_LIVE_BATCH,target_sweep=V15_SWEEP_FLOOR,
            conf_margin=0.045,seed=seed+10000*(j+1),deadline=cand_deadline)
        # Backward-compatible fallbacks: the fast MC currently returns a top-3
        # alliance share in addition to sweep. When available, use it as the
        # empirical two-plus podium signal; otherwise derive a conservative proxy.
        if 'mc_podium_2plus_prob' not in results[p]:
            share=float(results[p].get('mc_alliance_top3_share',0.0))
            sweep=float(results[p].get('mc_sweep_prob',0.0))
            # E[alliance podium share] = (2*P(2-only)+3*P(3))/3.
            # Rearranging gives a conservative lower bound for P(>=2).
            results[p]['mc_podium_2plus_prob']=float(np.clip((3.0*share-1.0)/2.0,0.0,1.0))

    def dual(r):
        pod=float(r.get('mc_podium_2plus_prob',0.0))
        sw=float(r.get('mc_sweep_prob',0.0))
        # Primary objective: get to >=90% podium probability.
        # Hard-floor behavior: sweep below 80% incurs a nonlinear penalty.
        pod_gap=max(0.0,V15_PODIUM_TARGET-pod)
        sweep_gap=max(0.0,V15_SWEEP_FLOOR-sw)
        return (V15_DUAL_TARGET_WEIGHT*pod + V15_SWEEP_FLOOR_WEIGHT*sw
                - V15_TARGET_PENALTY*(pod_gap**2 + 1.35*sweep_gap**2))

    ranked=sorted(names,key=lambda p:(dual(results[p]), results[p].get('mc_sweep_prob',0.0)),reverse=True)
    if len(ranked)>=2:
        a,b=ranked[:2]
        da,db=dual(results[a]),dual(results[b])
        overlap=(results[a]['mc_ci_low']<=results[b]['mc_ci_high'] and
                 results[b]['mc_ci_low']<=results[a]['mc_ci_high'])
        # Spend extra trials when the dual objective is genuinely close or when
        # either target is near its threshold.
        near_target=any(
            abs(results[p].get('mc_podium_2plus_prob',0.0)-V15_PODIUM_TARGET)<0.06
            or abs(results[p].get('mc_sweep_prob',0.0)-V15_SWEEP_FLOOR)<0.06
            for p in (a,b)
        )
        if overlap and (abs(da-db)<0.025 or near_target):
            # Only spend more trials on refinement if there's meaningfully
            # more time left -- otherwise this second forced-trial round is
            # exactly what stacks on top of the first pass and blows the
            # deadline on a slow CPU (each candidate's floor of trials runs
            # regardless of the deadline until it's hit).
            if time.monotonic() < deadline - 0.15:
                for j,p in enumerate((a,b)):
                    remaining=max(0.0, deadline - time.monotonic())
                    sub_deadline=time.monotonic() + remaining / max(1, 2 - j)
                    results[p]=v12_fast_candidate_mc(
                        tracker,team,p,min_trials=72,max_trials=V15_LIVE_MAX+48,
                        batch=V15_LIVE_BATCH,target_sweep=V15_SWEEP_FLOOR,conf_margin=0.03,
                        seed=seed+50000*(j+1),deadline=sub_deadline)
                    share=float(results[p].get('mc_alliance_top3_share',0.0))
                    results[p]['mc_podium_2plus_prob']=float(np.clip((3.0*share-1.0)/2.0,0.0,1.0))
    return results

def recommend_top3(tracker, weekly_games_df=None, team=None, live_mc=True, seed=0,
                   players=None, time_budget=None, **kwargs):
    """time_budget: wall-clock seconds for the whole call (default
    TOP3_TIME_BUDGET_SEC; the web app passes the long-mode budget).
    players: optional list of names to evaluate with this exact pipeline
    instead of the auto shortlist (the `check` command) -- see cmd_check."""
    budget=float(time_budget) if time_budget else TOP3_TIME_BUDGET_SEC
    n_custom=len(players) if players else 0
    if n_custom>3:
        budget*=n_custom/3.0   # keep the per-player share of the budget constant
    tracker._last_top3_budget=budget
    # v33/v34: the WHOLE call (candidate scoring + live MC) is kept inside
    # TOP3_TIME_BUDGET_SEC -- see the constant's comment above for why the
    # deadline now starts here, before v15_batch_top3 runs, instead of after.
    _start_ts=time.monotonic()
    team=tracker.my_slot if team is None else team
    _batch_deadline=_start_ts + budget*_V15_BATCH_TIME_FRACTION
    candidate=v15_batch_top3(tracker,team,deadline=_batch_deadline,players=(list(players) if players else None))
    _batch_elapsed=time.monotonic()-_start_ts
    if candidate.empty: return candidate, f'{team_label(team)} -- no players available.'
    _deadline=_start_ts + budget
    mc=_v15_adaptive_mc(tracker,team,candidate,seed=seed or tracker.overall,deadline=_deadline,
                        max_names=(n_custom or 3)) if live_mc else {}
    _total_elapsed=time.monotonic()-_start_ts
    print(f"[timing] candidate scoring: {_batch_elapsed:.2f}s | live MC: {_total_elapsed-_batch_elapsed:.2f}s | total: {_total_elapsed:.2f}s")
    for p,m in mc.items():
        for k,v in m.items(): candidate.loc[candidate.Player==p,k]=v
    for col in ('mc_sweep_prob','mc_season_sweep_prob','mc_team_champ_prob','mc_alliance_top3_share'):
        if col not in candidate.columns:
            candidate[col]=0.0
        candidate[col]=pd.to_numeric(candidate[col],errors='coerce').fillna(0.0)
    if 'mc_podium_2plus_prob' not in candidate.columns:
        # Conservative fallback for older MC rows.
        share=candidate['mc_alliance_top3_share'].fillna(0.0)
        candidate['mc_podium_2plus_prob']=((3.0*share-1.0)/2.0).clip(0.0,1.0)
    candidate['mc_podium_2plus_prob']=pd.to_numeric(candidate['mc_podium_2plus_prob'],errors='coerce').fillna(0.0)

    # Normalize supporting portfolio terms, while keeping the two probability
    # targets dominant. A hard-floor penalty makes an 85% podium / 65% sweep
    # candidate lose to an 88% podium / 80% sweep candidate.
    pod_gap=(V15_PODIUM_TARGET-candidate['mc_podium_2plus_prob']).clip(lower=0.0)
    sweep_gap=(V15_SWEEP_FLOOR-candidate['mc_sweep_prob']).clip(lower=0.0)
    candidate['v15_dual_target_score']=(
        V15_DUAL_TARGET_WEIGHT*candidate['mc_podium_2plus_prob']
        +V15_SWEEP_FLOOR_WEIGHT*candidate['mc_sweep_prob']
        -V15_TARGET_PENALTY*(pod_gap**2+1.35*sweep_gap**2)
    )
    candidate['v15_target_met']=(
        (candidate['mc_podium_2plus_prob']>=V15_PODIUM_TARGET)
        &(candidate['mc_sweep_prob']>=V15_SWEEP_FLOOR)
    )
    candidate['live_goal_score']=(
        0.62*candidate['v15_dual_target_score']+
        0.08*candidate['mc_season_sweep_prob'].fillna(0.0)+
        0.08*candidate['v13_portfolio_score']+
        0.05*candidate['v13_category_floor']+
        0.04*candidate['v13_balance']+
        0.03*candidate['v13_collision_avoidance']+
        0.03*candidate['v15_playoff_path']+
        0.03*candidate['v15_complementarity']+
        0.02*candidate['v15_min_strength']+
        0.02*candidate['v15_last_player_lookahead'])
    candidate=candidate.sort_values(['live_goal_score','v13_final_score'],ascending=False).reset_index(drop=True)
    candidate.insert(0,'Recommendation',np.arange(1,len(candidate)+1))
    candidate['goal_priority_score']=candidate['live_goal_score']
    candidate['alliance_goal_delta']=candidate['v13_portfolio_score']-candidate['v13_portfolio_score'].mean()
    candidate['reasoning']=[
        (f"Seeds={r['v13_alliance_seeds']}; byes={int(r['v13_bye_count'])}/3; "
         f"podium(2+)={r.get('mc_podium_2plus_prob',0):.1%}; sweep={r.get('mc_sweep_prob',0):.1%}; "
         f"targets={'YES' if bool(r.get('v15_target_met',False)) else 'NO'}; "
         f"floor={r['v13_category_floor']:.2f}; comp={r['v15_complementarity']:.2f}; "
         f"min-strength={r['v15_min_strength']:.2f}; path={r['v15_playoff_path']:.2f}; "
         f"over {int(r.get('mc_trials',0))} sims; CI sweep {r.get('mc_ci_low',0):.1%}-{r.get('mc_ci_high',0):.1%}.")
        for _,r in candidate.iterrows()
    ]
    candidate['plain_summary']=[
        f"Podium(2+) {r.get('mc_podium_2plus_prob',0):.1%}; sweep {r.get('mc_sweep_prob',0):.1%}; "
        f"targets {'met' if bool(r.get('v15_target_met',False)) else 'not met'}; seeds {r['v13_alliance_seeds']}; "
        f"floor {r['v13_category_floor']:.2f}; path {r['v15_playoff_path']:.2f}."
        for _,r in candidate.iterrows()
    ]
    nxt=next_own_pick_overall(tracker,after=tracker.overall,team=team)
    note=(f"{team_label(team)} -- v32 balanced-dominance alliance optimizer. Objective: "
          f"each alliance team drafts a balanced, all-categories-competitive roster (no punting -- "
          f"max_punts is locked to 0), and the alliance jointly pushes toward top-1/2/3 regular-season "
          f"seeds (podium probability >= {V15_PODIUM_TARGET:.0%}, all-3-seeds floor >= {V15_SWEEP_FLOOR:.0%}) "
          f"heading into the playoffs. 'complementarity' now means every ally staying strong in every "
          f"category (no team quietly relying on an ally to cover a weak one), not divergent rosters. "
          f"Regular-season head-to-head losses among allies are fine -- the shared goal is the championship. "
          f"Supporting terms: top-3/bye seeding, balance, category floor, weak-link strength, playoff path, "
          f"position runs, anti-alliance disruption, and scarcity lookahead. "
          f"Next Team {team} pick #{nxt if nxt else 'none'}.")
    if n_custom:
        note=(f"PLAYER CHECK for {team_label(team)}: the players you picked, run through the same scoring "
              f"and live simulations as the top-3 recommendation (ranked among themselves, not against the "
              f"full pool). ")+note
    return candidate.head(n_custom or 3),note

