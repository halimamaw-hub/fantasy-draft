def _v13_z(x):
    x=np.asarray(x,dtype=float)
    s=np.nanstd(x)
    return np.nan_to_num((x-np.nanmean(x))/s if s>1e-9 else x*0.0)

def _v13_portfolio_metrics(tracker, rosters, late_round=False):
    """Fast alliance-portfolio proxy from full projected rosters.

    Returns normalized metrics that can be combined across candidates without
    running the exact bracket for every candidate.
    """
    pool=tracker.pool
    prefix=tracker.zcol_prefix
    z=np.nan_to_num(pool[[f'{prefix}{c}' for c in CAT_COLS]].to_numpy(float),nan=0.0)
    idx={p:i for i,p in enumerate(pool['Player'])}
    po_cols=[f'zpo_ens_{c}' if f'zpo_ens_{c}' in pool.columns else f'{prefix}{c}' for c in CAT_COLS]
    po=np.nan_to_num(pool[po_cols].to_numpy(float),nan=0.0)
    strengths={}; floors={}; cat_totals={}
    for t,r in rosters.items():
        inds=[idx[p] for p in r if p in idx]
        if not inds:
            strengths[t]=0.0; floors[t]=0.0; cat_totals[t]=np.zeros(9); continue
        reg=z[inds].sum(axis=0); pla=po[inds].sum(axis=0)
        strengths[t]=float(reg.sum()+1.35*pla.sum())
        cat_totals[t]=reg+1.35*pla
        floors[t]=float(np.percentile(cat_totals[t],25))
    ordered=sorted(strengths,key=strengths.get,reverse=True)
    seed={t:i+1 for i,t in enumerate(ordered)}
    allies=set(V13_ALLIANCE)
    ally_seeds=[seed[t] for t in allies if t in seed]
    ally_strength=np.array([strengths[t] for t in allies],dtype=float)
    normalized=_v13_z(ally_strength)
    balance=float(-np.std(normalized)) if len(normalized) else 0.0
    top3=sum(s<=3 for s in ally_seeds)
    bye=sum(s<=6 for s in ally_seeds)
    two_plus=int(top3>=2)
    # direct category-floor measure: normalize each ally against the league's
    # corresponding category distribution, then take the weakest ally-category.
    league_cat=np.array([cat_totals[t] for t in range(1,tracker.teams+1)])
    cats_mean=league_cat.mean(axis=0); cats_std=league_cat.std(axis=0)+1e-9
    ally_floor_vals=[]
    for t in allies:
        zcats=(cat_totals[t]-cats_mean)/cats_std
        ally_floor_vals.append(float(np.percentile(zcats,25)))
    category_floor=float(np.mean(ally_floor_vals)) if ally_floor_vals else 0.0
    spread=max(ally_seeds)-min(ally_seeds) if ally_seeds else 0
    # Projected collision risk is a soft proxy: avoid the alliance occupying
    # adjacent middle seeds that are likely to collide after reseeding.
    collision_penalty=0.0
    pairs=[(a,b) for i,a in enumerate(ally_seeds) for b in ally_seeds[i+1:]]
    for a,b in pairs:
        d=abs(a-b)
        if d<=2: collision_penalty += (3-d)*0.5
    collision_avoidance=-collision_penalty
    portfolio_value=float(np.mean(ally_strength)) if len(ally_strength) else 0.0
    return {
        'seed':seed,'ally_seeds':tuple(sorted(ally_seeds)),
        'ally_seed_map':{int(t):int(seed[t]) for t in sorted(allies) if t in seed},
        'top3_count':top3,'bye_count':bye,'two_plus_top3':two_plus,
        'balance':balance,'category_floor':category_floor,
        'collision_avoidance':collision_avoidance,
        'portfolio_value':portfolio_value,
        'strengths':strengths,'floors':floors,'cat_totals':cat_totals,
        'spread':spread,
    }


