def playoff_weeks_from_schedule(weekly_games_df, n_weeks=4):
    """
    FIX #24 (foot-gun, not a crash): table_data_fixed.csv actually contains
    weeks 19-24, but DEFAULT_PLAYOFF_WEEKS is (19, 20, 21, 22), so every
    schedule-aware number -- playoff-game weighting, the weekly round robin,
    the whole bracket -- silently ran on the FIRST four weeks in the file
    rather than the last four. That is a plausible default only if the file
    happens to start at the playoffs. Nothing errored, which is what makes it
    dangerous. Use this to take the last `n_weeks` in the file, and pass the
    same tuple to attach_playoff_schedule(), DraftTracker() and
    simulate_playoff_bracket().
    """
    weeks = sorted(int(w) for w in weekly_games_df.index)
    if len(weeks) < n_weeks:
        raise ValueError(f"schedule has only {len(weeks)} week(s) {weeks}, need {n_weeks}")
    chosen = tuple(weeks[-n_weeks:])
    if len(weeks) > n_weeks:
        print(f"[playoff_weeks_from_schedule] schedule covers weeks {weeks}; "
              f"using the last {n_weeks} ({list(chosen)}) as the playoff window. "
              f"Pass playoff_weeks explicitly if your league's bracket sits elsewhere.")
    return chosen

def _norm_name(s):
    """
    FIX #27: separators were DELETED rather than spaced, so "Shai Gilgeous
    Alexander" normalised to "shai gilgeousalexander" and did not match
    "Shai Gilgeous-Alexander" -> "shai gilgeousalexander"... it did, but the
    reverse case did not: typing the name WITHOUT the hyphen gave
    "shai gilgeous alexander", a different string. update_drafted() reported it
    as COULD NOT MATCH and silently skipped the pick. On draft day people type
    names without punctuation constantly, and a skipped pick corrupts every
    downstream roster. Separators now collapse to a single space on both sides.
    """
    s = unicodedata.normalize("NFKD", str(s)).encode("ascii", "ignore").decode()
    s = s.strip().lower()
    s = re.sub(r"[\u2019'`.]", "", s)   # De'Aaron -> DeAaron, P.J. -> PJ, Jr. -> Jr
    s = re.sub(r"[-_/]", " ", s)         # Gilgeous-Alexander -> Gilgeous Alexander
    s = re.sub(r"[^a-z0-9 ]", "", s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"\s+(jr|sr|ii|iii|iv|v)$", "", s)
    s = s.strip()
    return NAME_ALIASES.get(s, s)

def load_players(csv_path, pool_size=None, stats_csv_path=None):
    df = pd.read_csv(csv_path)
    for c in ["RkOv", "ADP"] + CAT_COLS:
        df[c] = pd.to_numeric(df[c], errors="coerce")

    df = _normalize_pct_scale(df, label="base pool: ")

    df["has_real_adp"] = df["ADP"].notna()
    adp_offset = df.loc[df["has_real_adp"], "ADP"].max() if df["has_real_adp"].any() else 0
    df["ADP"] = df["ADP"].where(df["has_real_adp"], df["RkOv"] + adp_offset)

    df = df.dropna(subset=["ADP"] + CAT_COLS).sort_values("ADP").reset_index(drop=True)

    # FIX #17: the Fantrax export carries rows for players with no prior-season
    # line at all (PTS/REB/AST/FG% all exactly 0 -- injured-out, rookies,
    # unsigned). dropna() keeps them because 0 is not NaN. They then hit
    # FGA_pg_est = PTS / (2 * FG%), i.e. 0/0 -> NaN, and one such player
    # anywhere on a roster turned that roster's entire weekly FGM total into
    # NaN, which compare_category_totals then silently scored as a tie. In the
    # supplied data, Ben Simmons and Mario Hezonja were doing exactly that.
    #
    # They are NOT dropped: names like Haliburton, Kyrie Irving and Lillard sit
    # in this bucket, they will be drafted by somebody, and record_pick() has to
    # be able to log them during a live draft. They are flagged instead, and
    # FIX #17b below makes their attempt estimates 0 rather than NaN so they
    # contribute nothing instead of poisoning a whole team's percentages.
    df["no_prior_stats"] = (df[["PTS", "REB", "AST", "FG%"]].abs().sum(axis=1) == 0)
    if df["no_prior_stats"].any():
        flagged = list(df.loc[df["no_prior_stats"], "Player"])
        print(f"[load_players] {len(flagged)} player(s) have an all-zero prior-season "
              f"line and will score 0 in every category (still draftable/loggable): "
              f"{flagged[:8]}{' ...' if len(flagged) > 8 else ''}")

    df["isG"] = df["Position"].str.contains("G")
    df["isF"] = df["Position"].str.contains("F")
    df["isC"] = df["Position"].str.contains("C")

    pool = (df if pool_size is None else df.head(pool_size)).copy()

    pool["has_attempts"] = False
    if stats_csv_path is not None:
        stats = pd.read_csv(stats_csv_path)
        for c in ["GP", "FGM", "FGA", "FTM", "FTA"]:
            stats[c] = pd.to_numeric(stats[c], errors="coerce")
        stats["norm"] = stats["PLAYER"].map(_norm_name)
        stats = stats.sort_values("GP", ascending=False).drop_duplicates("norm")
        stats["FGA_pg"] = stats["FGA"] / stats["GP"]
        stats["FTA_pg"] = stats["FTA"] / stats["GP"]
        pool["norm"] = pool["Player"].map(_norm_name)
        pool = pool.merge(stats[["norm", "FGA_pg", "FTA_pg", "GP"]], on="norm", how="left")
        pool["has_attempts"] = pool["FGA_pg"].notna() & (pool["GP"] >= 10)
    return pool

def compute_zscores(pool):
    pool = pool.copy()
    mean_pts = pool["PTS"].mean()
    has_att = pool.get("has_attempts", pd.Series(False, index=pool.index))
    has_att = has_att.fillna(False).astype(bool)

    if has_att.any():
        avg_fg_pct = (pool.loc[has_att, "FG%"] * pool.loc[has_att, "FGA_pg"]).sum() / pool.loc[has_att, "FGA_pg"].sum()
        avg_ft_pct = (pool.loc[has_att, "FT%"] * pool.loc[has_att, "FTA_pg"]).sum() / pool.loc[has_att, "FTA_pg"].sum()

        fg_impact_real = (pool["FG%"] - avg_fg_pct) * pool["FGA_pg"]
        ft_impact_real = (pool["FT%"] - avg_ft_pct) * pool["FTA_pg"]
        proxy_scale_fg = (pool.loc[has_att, "FGA_pg"] / mean_pts).mean()
        proxy_scale_ft = (pool.loc[has_att, "FTA_pg"] / mean_pts).mean()
        fg_impact_proxy = (pool["FG%"] - pool["FG%"].mean()) * pool["PTS"] * proxy_scale_fg
        ft_impact_proxy = (pool["FT%"] - pool["FT%"].mean()) * pool["PTS"] * proxy_scale_ft

        pool["FG_impact"] = np.where(has_att, fg_impact_real, fg_impact_proxy)
        pool["FT_impact"] = np.where(has_att, ft_impact_real, ft_impact_proxy)

        fga_pg_col = pool["FGA_pg"] if "FGA_pg" in pool.columns else pd.Series(np.nan, index=pool.index)
        fta_pg_col = pool["FTA_pg"] if "FTA_pg" in pool.columns else pd.Series(np.nan, index=pool.index)
        pool["FGA_pg_est"] = np.where(has_att, fga_pg_col, pool["PTS"] * proxy_scale_fg)
        pool["FTA_pg_est"] = np.where(has_att, fta_pg_col, pool["PTS"] * proxy_scale_ft)
    else:
        pool["FG_impact"] = (pool["FG%"] - pool["FG%"].mean()) * (pool["PTS"] / mean_pts)
        pool["FT_impact"] = (pool["FT%"] - pool["FT%"].mean()) * (pool["PTS"] / mean_pts)
        pool["FGA_pg_est"] = pool["PTS"] / (2.0 * pool["FG%"].replace(0, np.nan))
        pool["FTA_pg_est"] = pool["PTS"] * 0.15

    # FIX #17b: belt-and-braces. Any remaining non-finite or negative attempt
    # estimate becomes 0 attempts rather than NaN, so a single odd player can't
    # NaN out an entire team's weekly FG%/FT%.
    for col in ("FGA_pg_est", "FTA_pg_est"):
        v = pd.to_numeric(pool[col], errors="coerce")
        pool[col] = v.where(np.isfinite(v) & (v >= 0), 0.0)

    z = lambda s: (s - s.mean()) / s.std()
    pool["z_FG%"] = z(pool["FG_impact"])
    pool["z_FT%"] = z(pool["FT_impact"])
    pool["z_3PTM"] = z(pool["3PTM"])
    pool["z_PTS"] = z(pool["PTS"])
    pool["z_REB"] = z(pool["REB"])
    pool["z_AST"] = z(pool["AST"])
    pool["z_ST"] = z(pool["ST"])
    pool["z_BLK"] = z(pool["BLK"])
    pool["z_TO"] = -z(pool["TO"])
    pool["total_z"] = pool[[f"z_{c}" for c in CAT_COLS]].sum(axis=1)
    return pool

def _normalize_pct_scale(df, cols=("FG%", "FT%"), label=""):
    """
    FIX #16 (CRITICAL): the three data sources disagree on the unit for FG%/FT%.
    Fantrax and proj2 (table.csv) report fractions (.512), proj1
    (fantasy_basketball_rankings.csv) reports percentage points (51.2). Nothing
    reconciled them, so rens_/rproj_ FG% and FT% were the mean of 0.51 and 51.2
    -- i.e. ~17, not a percentage at all. Every weekly/bracket simulation then
    computed FGM = FG% * FGA off that number, and since only top-150 players
    appear in proj1, a team's FG%/FT% total was effectively a count of how many
    of its players were on that list. Measured on a completed mock draft:
    corr(team FG% total, # of top-150 players rostered) = 0.85. Two of nine
    categories were decided by list membership rather than shooting.

    This rescales any 0-100 column down to a 0-1 fraction at load time, so every
    source is on one unit before anything is averaged. Detection uses the median
    (robust to the zero-stat placeholder rows in the Fantrax export).
    """
    for c in cols:
        if c not in df.columns:
            continue
        med = pd.to_numeric(df[c], errors="coerce").median()
        if pd.notna(med) and med > 1.5:
            df[c] = pd.to_numeric(df[c], errors="coerce") / 100.0
            print(f"[_normalize_pct_scale] {label}{c} looked like percentage points "
                  f"(median {med:.1f}) -- rescaled to a 0-1 fraction.")
    return df

def _load_projection_csv(csv_path, name_col, team_col, gp_col, pts_col, tpm_col,
                          reb_col, ast_col, stl_col, blk_col, to_col, fg_col, ft_col,
                          fga_col=None, fta_col=None, minutes_col=None, contract_col=None,
                          sep=","):
    df = pd.read_csv(csv_path, sep=sep)
    rename = {name_col: "Player", team_col: "Team"}
    # Any stat column can be omitted (this source just doesn't report it --
    # e.g. the ESPN export below has no turnovers column). Missing columns
    # are filled with NaN instead of raising, and merge_projections()'s
    # skipna=True ensemble mean already treats a source-level NaN as "this
    # source has no opinion here" rather than a zero.
    optional = {"GP": gp_col, "PTS": pts_col, "3PTM": tpm_col, "REB": reb_col,
                "AST": ast_col, "ST": stl_col, "BLK": blk_col, "TO": to_col,
                "FG%": fg_col, "FT%": ft_col}
    for out_name, src_col in optional.items():
        if src_col:
            rename[src_col] = out_name
    if fga_col: rename[fga_col] = "FGA_pg"
    if fta_col: rename[fta_col] = "FTA_pg"
    if minutes_col: rename[minutes_col] = "Minutes_pg"
    if contract_col: rename[contract_col] = "Contract"
    df = df.rename(columns=rename)
    for out_name, src_col in optional.items():
        if not src_col and out_name not in df.columns:
            df[out_name] = np.nan

    num_cols = list(optional.keys())
    if fga_col: num_cols.append("FGA_pg")
    if fta_col: num_cols.append("FTA_pg")
    if minutes_col: num_cols.append("Minutes_pg")
    for c in num_cols:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    # A source with no GP column at all (rather than a genuinely missing GP
    # value) shouldn't lose every one of its rows to the GP-based sort below.
    if gp_col is None:
        df["GP"] = df["GP"].fillna(0.0)

    df = _normalize_pct_scale(df, label=f"{csv_path.split('/')[-1]}: ")

    if fga_col and fta_col:
        df["has_attempts"] = df["FGA_pg"].notna() & df["FTA_pg"].notna()
    else:
        df["has_attempts"] = False

    df["norm"] = df["Player"].map(_norm_name)
    df = df.dropna(subset=["PTS", "norm"])
    df = df.sort_values("GP", ascending=False).drop_duplicates("norm")

    keep = ["norm", "Player", "Team"] + num_cols + ["has_attempts"]
    if contract_col: keep.append("Contract")
    return df[[c for c in keep if c in df.columns]].reset_index(drop=True)

def merge_projections(pool, proj1_path=None, proj2_path=None, proj3_path=None, proj4_path=None):
    """Blend up to four external projection sources into the pool.

    proj1_path: fantasy_basketball_rankings.csv-style export (Player, GP, ...)
    proj2_path: table.csv-style export (Player Name, Games Played, ...; ';'-sep)
    proj3_path: ESPN-style export (Name, GP, MIN, FGM/FGA, FTM/FTA, TO, ...).
                v33: the ESPN export now includes GP and TO (it previously
                didn't -- both were tolerated as missing via
                _load_projection_csv, and still are if a future ESPN export
                drops them again).
    proj4_path: RotoBaller-style export (Player, FG/FGA/FGpct, FT/FTA/FTpct,
                FG3, RB, AST, BLK, STL, TO, Min, ...). No GP column -- handled
                the same way proj3 used to be (see _load_projection_csv).

    Any subset may be supplied. zproj_/rproj_ are the mean across whichever
    projection sources were given (1-4); zens_/rens_ additionally fold
    in last season's actuals (z_/r_). A category a given source doesn't
    report is skipped for that source via skipna=True rather than pulling
    the ensemble toward zero.
    """
    pool = pool.copy()
    pool["norm"] = pool["Player"].map(_norm_name)

    z_last_full = compute_zscores(pool)
    for c in CAT_COLS:
        pool[f"z_{c}"] = z_last_full[f"z_{c}"]
        pool[f"r_{c}"] = pool[c]
    pool["r_FGA_pg"] = z_last_full["FGA_pg_est"].values
    pool["r_FTA_pg"] = z_last_full["FTA_pg_est"].values

    proj_zsets = {}
    proj_rsets = {}
    proj_minutes = {}
    _RAW_KEEP = CAT_COLS + ["FGA_pg_est", "FTA_pg_est"]

    proj_specs = {
        "proj1": dict(
            path=proj1_path, name_col="Player", team_col="Team", gp_col="GP",
            pts_col="PTS", tpm_col="3PM", reb_col="REB", ast_col="AST",
            stl_col="STL", blk_col="BLK", to_col="TO", fg_col="FG%", ft_col="FT%",
        ),
        "proj2": dict(
            path=proj2_path, name_col="Player Name", team_col="NBA Team",
            gp_col="Games Played", pts_col="PTS", tpm_col="TPM", reb_col="REB",
            ast_col="AST", stl_col="STL", blk_col="BLK", to_col="TOV",
            fg_col="FG%", ft_col="FT%", fga_col="FGA", fta_col="FTA",
            minutes_col="Total Minutes", contract_col="Contract", sep=";",
        ),
        "proj3": dict(
            # v33: the supplied ESPN export now has both GP and TO columns
            # (it previously had neither). gp_col/to_col updated accordingly
            # -- both stay optional in _load_projection_csv, so a future
            # ESPN export missing either one again won't break anything.
            path=proj3_path, name_col="Name", team_col="Team", gp_col="GP",
            pts_col="PTS", tpm_col="3PM", reb_col="REB", ast_col="AST",
            stl_col="STL", blk_col="BLK", to_col="TO", fg_col="FG%", ft_col="FT%",
            fga_col="FGA", fta_col="FTA", minutes_col="MIN",
        ),
        "proj4": dict(
            # RotoBaller export: no GP column (handled like the old ESPN
            # export -- see _load_projection_csv's gp_col=None branch).
            path=proj4_path, name_col="Player", team_col="Team", gp_col=None,
            pts_col="PTS", tpm_col="FG3", reb_col="RB", ast_col="AST",
            stl_col="STL", blk_col="BLK", to_col="TO", fg_col="FGpct", ft_col="FTpct",
            fga_col="FGA", fta_col="FTA", minutes_col="Min",
        ),
    }

    for key, spec in proj_specs.items():
        path = spec.pop("path")
        if not path:
            continue
        proj = _load_projection_csv(path, **spec)
        aligned = pool[["norm"]].merge(proj, on="norm", how="left")
        aligned["has_attempts"] = aligned["has_attempts"].where(aligned["has_attempts"].notna(), False).astype(bool)
        z = compute_zscores(aligned)
        proj_zsets[key] = z[[f"z_{c}" for c in CAT_COLS]].reset_index(drop=True)
        proj_rsets[key] = z[_RAW_KEEP].reset_index(drop=True)
        n_matched = aligned["PTS"].notna().sum()
        print(f"[merge_projections] {key}: matched {n_matched}/{len(pool)} pool players")

        # v33: also keep this source's own per-game numbers on the pool,
        # under its own rcol_prefix (see _SOURCE_PREFIX_MAP), so catrank/h2h
        # can be run against a single named source instead of only the
        # blended rproj_/rens_ ensemble. A player this source doesn't cover
        # gets NaN here (same "no opinion" behavior as the ensemble columns);
        # team_week_stat_totals already treats that as 0 for the week rather
        # than erroring, since raw[c] * NaN * games only ever touches players
        # actually on a roster, and unmatched players are league-wide rare.
        src_prefix = _SOURCE_PREFIX_MAP.get(key)
        if src_prefix:
            src_r = proj_rsets[key]  # == z[_RAW_KEEP], already built just above
            # A player this single source has no opinion on gets NaN here from
            # the left-merge above. Filled to 0 (0 stats, 0 FGA/FTA) rather
            # than left as NaN -- same treatment the base pool already gives
            # true zero-stat rookies (FIX #17), so one unmatched player can't
            # NaN-poison a whole roster's weekly total for a single-source
            # catrank/h2h run the way an unfilled NaN would.
            for c in CAT_COLS:
                pool[f"{src_prefix}{c}"] = src_r[c].fillna(0.0).values
            pool[f"{src_prefix}FGA_pg"] = src_r["FGA_pg_est"].fillna(0.0).values
            pool[f"{src_prefix}FTA_pg"] = src_r["FTA_pg_est"].fillna(0.0).values
        if "Minutes_pg" in proj.columns:
            extra = pool[["norm"]].merge(proj[["norm", "Minutes_pg"]], on="norm", how="left")
            proj_minutes[key] = extra["Minutes_pg"].values
        if "Contract" in proj.columns:
            extra = pool[["norm"]].merge(proj[["norm", "Contract"]], on="norm", how="left")
            pool["proj2_contract"] = extra["Contract"].values

    if proj_minutes:
        stacked_minutes = pd.DataFrame(proj_minutes)
        pool["proj2_minutes_pg"] = stacked_minutes.mean(axis=1, skipna=True).values

    if proj_zsets:
        for cat in CAT_COLS:
            stacked = pd.concat([proj_zsets[k][f"z_{cat}"] for k in proj_zsets], axis=1)
            pool[f"zproj_{cat}"] = stacked.mean(axis=1, skipna=True).values

            stacked_ens = pd.concat(
                [pool[f"z_{cat}"].reset_index(drop=True)] + [proj_zsets[k][f"z_{cat}"] for k in proj_zsets],
                axis=1,
            )
            pool[f"zens_{cat}"] = stacked_ens.mean(axis=1, skipna=True).values

        for cat in CAT_COLS:
            stacked = pd.concat([proj_rsets[k][cat] for k in proj_rsets], axis=1)
            pool[f"rproj_{cat}"] = stacked.mean(axis=1, skipna=True).values
            stacked_ens = pd.concat(
                [pool[f"r_{cat}"].reset_index(drop=True)] + [proj_rsets[k][cat] for k in proj_rsets],
                axis=1,
            )
            pool[f"rens_{cat}"] = stacked_ens.mean(axis=1, skipna=True).values

        for est_col, out_name in [("FGA_pg_est", "FGA_pg"), ("FTA_pg_est", "FTA_pg")]:
            stacked = pd.concat([proj_rsets[k][est_col] for k in proj_rsets], axis=1)
            pool[f"rproj_{out_name}"] = stacked.mean(axis=1, skipna=True).values
            stacked_ens = pd.concat(
                [pool[f"r_{out_name}"].reset_index(drop=True)] + [proj_rsets[k][est_col] for k in proj_rsets],
                axis=1,
            )
            pool[f"rens_{out_name}"] = stacked_ens.mean(axis=1, skipna=True).values
        if len(proj_zsets) == 1:
            print(f"[merge_projections] Only {list(proj_zsets)[0]} supplied -- "
                  f"'zproj_'/'rproj_' equal that one source until more are added.")

    # FIX #28 (cont.): surface who ended up with no projection at all, sorted by
    # ADP, so a draft-relevant miss cannot hide behind a match-count summary.
    if proj_zsets:
        probe = f"zproj_{CAT_COLS[0]}" if f"zproj_{CAT_COLS[0]}" in pool.columns else None
        if probe is not None:
            miss = pool.loc[pool[probe].isna(), ["Player", "ADP"]].sort_values("ADP")
            near = miss[miss["ADP"] <= 200]
            if len(near):
                print(f"[merge_projections] {len(miss)} pool player(s) matched NO projection "
                      f"source; {len(near)} of them inside ADP 200 and will be scored on "
                      f"last-year data alone: {list(near['Player'])}. Add a NAME_ALIASES entry "
                      f"if that is a naming mismatch rather than a genuinely unprojected player.")

    pool.drop(columns=["norm"], inplace=True)
    return pool

def apply_minutes_confidence(pool, prefixes=None, min_minutes=22.0):
    pool = pool.copy()
    if "proj2_minutes_pg" not in pool.columns:
        print("[apply_minutes_confidence] No minutes-per-game data attached -- "
              "call merge_projections(..., proj2_path=... and/or proj3_path=...) "
              "first (both report MIN/Total Minutes; ESPN's MIN is used too if "
              "present, blended with proj2's). Skipping.")
        return pool

    if prefixes is None:
        base_prefixes = ["zproj_", "zens_", "rproj_", "rens_"]
        po_map = {"zproj_": "zpo_proj_", "zens_": "zpo_ens_"}
        prefixes = list(base_prefixes)
        for src, po in po_map.items():
            if f"{po}{CAT_COLS[0]}" in pool.columns:
                prefixes.append(po)
        prefixes = tuple(prefixes)

    discount = (pool["proj2_minutes_pg"] / min_minutes).clip(upper=1.0).fillna(1.0)
    pool["minutes_discount"] = discount
    for prefix in prefixes:
        # FIX #18: the raw ('r*') sets are real per-game stat lines, and FG%/FT%
        # in them are RATES, not volume. Scaling a rate by a minutes factor said
        # a 12-minute player shoots half as accurately as he really does, and
        # because FGM is later derived as FG% x FGA (with FGA already
        # discounted), the volume discount was also applied twice. Discount
        # volume only here; the z-sets are impact scores, where scaling the
        # whole line by playing time is the intended behaviour, so they keep the
        # original treatment.
        if prefix.startswith("z"):
            cols = list(CAT_COLS)
        else:
            cols = list(COUNTING_COLS) + ["FGA_pg", "FTA_pg"]
        for c in cols:
            col = f"{prefix}{c}"
            if col in pool.columns:
                pool[col] = pool[col] * discount
    pool["contract_note"] = pool.get("proj2_contract", pd.Series(index=pool.index, dtype=object)).fillna("")
    n_flagged = (pool["contract_note"] != "").sum()
    n_discounted = (discount < 1.0).sum()
    print(f"[apply_minutes_confidence] discounted {n_discounted} players below "
          f"{min_minutes} proj. minutes/game across prefixes {prefixes}; "
          f"flagged {n_flagged} with contract notes. Safe to call before OR "
          f"after attach_playoff_schedule() now.")
    return pool

def _build_full_pick_order(teams=10, rounds=14, reversal_round=3):
    order, prev_order, seq = list(range(1, teams + 1)), None, []
    for rnd in range(1, rounds + 1):
        if rnd == 1:
            this_order = order
        elif rnd == 2:
            this_order = list(reversed(order))
        elif rnd == reversal_round:
            this_order = prev_order
        else:
            this_order = list(reversed(prev_order))
        seq.extend(this_order)
        prev_order = this_order
    return seq

def solve_roster(pool, current_roster_names=None, roster_size=14,
                  pos_need=("G", "F", "C"), pos_min=(2, 2, 1),
                  max_punts=2, BIGM=200, zcol_prefix=None, cat_weights=None,
                  punt_incidental_credit=0.05):
    zcol_prefix = _resolve_zcol_prefix(pool, zcol_prefix)
    missing = [c for c in CAT_COLS if f"{zcol_prefix}{c}" not in pool.columns]
    if missing:
        raise ValueError(
            f"pool is missing '{zcol_prefix}'-prefixed columns for {missing}. "
            "Call attach_playoff_schedule(pool) after compute_zscores()/"
            "merge_projections() to get playoff-weighted columns, or pass "
            "zcol_prefix=\"z_\" / \"zproj_\" / \"zens_\" for a non-playoff-"
            "weighted prediction set."
        )
    cat_weights = cat_weights or {}
    w = np.array([cat_weights.get(c, 1.0) for c in CAT_COLS])

    current_roster_names = current_roster_names or []
    avail = pool[~pool["Player"].isin(current_roster_names)].reset_index(drop=True)
    have = pool[pool["Player"].isin(current_roster_names)]

    n, ncat = len(avail), len(CAT_COLS)
    picks_needed = roster_size - len(current_roster_names)
    nvar = n + ncat + ncat

    c_obj = np.zeros(nvar)
    c_obj[n + ncat:] = -1.0
    for k, cat in enumerate(CAT_COLS):
        zvec = avail[f"{zcol_prefix}{cat}"].values * w[k]
        c_obj[:n] += -punt_incidental_credit * zvec

    constraints = []
    row = np.zeros(nvar); row[:n] = 1
    constraints.append(LinearConstraint(row, picks_needed, picks_needed))

    for pos, mn in zip(pos_need, pos_min):
        have_ct = have["Position"].str.contains(pos).sum() if len(have) else 0
        need = max(0, mn - have_ct)
        row = np.zeros(nvar)
        row[:n] = avail["Position"].str.contains(pos).astype(float).values
        constraints.append(LinearConstraint(row, need, np.inf))

    row = np.zeros(nvar); row[n:n + ncat] = 1
    constraints.append(LinearConstraint(row, 0, max_punts))

    have_z = {cat: (have[f"{zcol_prefix}{cat}"].sum() if len(have) else 0.0) for cat in CAT_COLS}
    for k, cat in enumerate(CAT_COLS):
        zvec = avail[f"{zcol_prefix}{cat}"].values * w[k]
        row = np.zeros(nvar)
        row[:n] = -zvec
        row[n + k] = -BIGM
        row[n + ncat + k] = 1
        constraints.append(LinearConstraint(row, -np.inf, have_z[cat] * w[k]))
        row2 = np.zeros(nvar)
        row2[n + k] = BIGM
        row2[n + ncat + k] = 1
        constraints.append(LinearConstraint(row2, -np.inf, BIGM))

    integrality = np.zeros(nvar); integrality[:n + ncat] = 1
    lb, ub = np.zeros(nvar), np.ones(nvar)
    lb[n + ncat:], ub[n + ncat:] = -BIGM, BIGM

    res = milp(c_obj, constraints=constraints, integrality=integrality,
               bounds=Bounds(lb, ub))
    if not res.success:
        raise RuntimeError("MILP failed: " + res.message)

    x, punts = res.x[:n], res.x[n:n + ncat]
    chosen = avail.iloc[np.where(x > 0.5)[0]]
    punted_cats = [CAT_COLS[i] for i in range(ncat) if punts[i] > 0.5]
    return chosen, punted_cats, -res.fun

