def attach_playoff_schedule(pool, weekly_games_df=None, playoff_weeks=DEFAULT_PLAYOFF_WEEKS):
    pool = pool.copy()
    if weekly_games_df is not None:
        missing_weeks = [w for w in playoff_weeks if w not in weekly_games_df.index]
        if missing_weeks:
            raise ValueError(
                f"attach_playoff_schedule: playoff_weeks {list(playoff_weeks)} don't match "
                f"weekly_games_df -- week(s) {missing_weeks} not found. Your schedule file's "
                f"actual weeks are: {list(weekly_games_df.index)}. Pass the correct 4 weeks "
                f"explicitly and use that same playoff_weeks tuple everywhere else "
                f"(DraftTracker(...), simulate_playoff_bracket(...), etc.)."
            )
        team_playoff_games = weekly_games_df.loc[list(playoff_weeks)].sum(axis=0).to_dict()
    else:
        print("[attach_playoff_schedule] No weekly_games_df given -- falling back to "
              "a legacy hardcoded playoff-game guess. Strongly prefer "
              "weekly_games_df=load_weekly_games_table(csv_path) for real schedule data.")
        team_playoff_games = _LEGACY_TEAM_PLAYOFF_GAMES

    avg_games = np.mean(list(team_playoff_games.values()))
    pool["playoff_games"] = pool["Team"].map(team_playoff_games).fillna(avg_games)
    ratio = pool["playoff_games"] / avg_games
    for src_prefix, po_prefix in _PLAYOFF_PREFIX_MAP.items():
        if f"{src_prefix}{CAT_COLS[0]}" not in pool.columns:
            continue
        for c in CAT_COLS:
            pool[f"{po_prefix}{c}"] = pool[f"{src_prefix}{c}"] * ratio
    return pool

