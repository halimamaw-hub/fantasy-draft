import textwrap as _textwrap


def _t3_num(row, key, default=None):
    """Read a numeric value from a row; NaN / missing / non-numeric -> default."""
    try:
        v = row.get(key, default)
    except Exception:
        return default
    if v is None:
        return default
    try:
        v = float(v)
    except (TypeError, ValueError):
        return default
    return default if math.isnan(v) else v


def _t3_seeds(row):
    """Projected regular-season seeds of the alliance teams, e.g. [3, 5, 9]."""
    s = row.get("v13_alliance_seeds") if hasattr(row, "get") else None
    if s is None:
        return []
    try:
        return [int(x) for x in s]
    except (TypeError, ValueError):
        return []


def _t3_seed_map(row):
    """Projected regular-season seed of EACH alliance team: [{'team':9,'label':..,'seed':3}, ...],
    ordered by team number (so the same ally is always in the same spot)."""
    m = row.get("v13_alliance_seed_map") if hasattr(row, "get") else None
    if not isinstance(m, dict):
        return []
    out = []
    for t in sorted(m):
        try:
            out.append({"team": int(t), "label": team_label(int(t)), "seed": int(m[t])})
        except (TypeError, ValueError):
            continue
    return out


def _t3_pct(x, digits=1):
    return "--" if x is None else f"{x * 100:.{digits}f}%"


def _t3_signed(x):
    return "--" if x is None else f"{x:+.2f}"


