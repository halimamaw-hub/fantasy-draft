def load_weekly_games_table(csv_path):
    """
    v10: rewritten again for NBASchedule_-_Sheet1.csv, which is laid out
    differently from both table_data_fixed.csv (v8) and schedule_grid.csv
    (v9):
      - NO header row at the top -- row 0 is week-1 data directly.
      - The team-code header is the LAST row of the file instead
        (",", ",", "ATL", "BKN", ...).
      - It has all 30 teams, but the header row has 32 columns because two
        team codes (UTA, WAS) are duplicated at the end -- an export
        artifact, not real columns; the duplicates are dropped.
    Rather than hardcode "header is row N", the header row is detected as
    whichever row's cells (from column 3 on) look like team codes (short,
    non-numeric strings) instead of week/date/game-count numbers. Falls back
    to a normal top-header CSV (table_data_fixed.csv / schedule_grid.csv
    style, including schedule_grid.csv's GAMES/MAX WEEKS/AVG EASE summary
    rows) if no such row is found. Any of the 30 real NBA teams still
    missing after this is filled with the per-week average of the teams
    that ARE present, with a one-time warning -- see ALL_NBA_TEAMS.
    """
    raw = pd.read_csv(csv_path, header=None, dtype=str)

    def _looks_like_team_row(row):
        cells = [c for c in row[2:] if isinstance(c, str) and c.strip() not in ("", "nan")]
        if len(cells) < 5:
            return False
        return all(c.strip().isalpha() and 2 <= len(c.strip()) <= 4 for c in cells)

    header_idx = None
    for i in range(len(raw)):
        if _looks_like_team_row(raw.iloc[i].tolist()):
            header_idx = i
            break

    if header_idx is not None:
        header_cells = raw.iloc[header_idx].tolist()
        team_cols, seen = [], set()
        for j, c in enumerate(header_cells):
            if not isinstance(c, str) or not c.strip() or c.strip().lower() == "nan":
                continue
            code = _CODE_FIX.get(c.strip(), c.strip())
            if code in seen:
                continue  # drop duplicate trailing columns (e.g. UTA/WAS repeated)
            seen.add(code)
            team_cols.append((j, code))

        data_rows = raw.drop(index=header_idx)
        weeks = pd.to_numeric(data_rows[0], errors="coerce")
        keep = weeks.notna()
        data_rows, weeks = data_rows[keep], weeks[keep].astype(int)
        dates = data_rows[1] if 1 in data_rows.columns else None

        out = pd.DataFrame(index=weeks.values)
        out.index.name = "Week"
        for j, code in team_cols:
            if j in data_rows.columns:
                out[code] = pd.to_numeric(data_rows[j], errors="coerce").values
        df = out.sort_index()
        if dates is not None:
            df.attrs["dates"] = pd.Series(dates.values, index=weeks.values).sort_index()
    else:
        # Fallback: old top-header layout (table_data_fixed.csv /
        # schedule_grid.csv), including schedule_grid.csv's blank-Week
        # summary rows (GAMES / MAX WEEKS / AVG EASE), which are dropped.
        df = pd.read_csv(csv_path)
        df["Week"] = pd.to_numeric(df["Week"], errors="coerce")
        df = df.dropna(subset=["Week"])
        df["Week"] = df["Week"].astype(int)
        df = df.set_index("Week")
        dates = df.pop("Date") if "Date" in df.columns else None
        df = df.rename(columns=lambda c: _CODE_FIX.get(c, c))
        df = df.apply(pd.to_numeric, errors="coerce")
        if dates is not None:
            df.attrs["dates"] = dates

    missing_teams = [t for t in ALL_NBA_TEAMS if t not in df.columns]
    if missing_teams:
        week_avg = df.mean(axis=1)
        for t in missing_teams:
            df[t] = week_avg
        print(f"[load_weekly_games_table] WARNING: {csv_path} has no column for "
              f"{len(missing_teams)} team(s): {missing_teams}. Filled with each "
              f"week's average games-played across the teams that ARE in the file, "
              f"so players on these teams don't get zeroed out. Replace the file "
              f"with a full 30-team export for exact numbers if this list is non-empty.")
    else:
        print(f"[load_weekly_games_table] loaded {csv_path}: all 30 NBA teams present, "
              f"weeks {int(df.index.min())}-{int(df.index.max())}.")
    return df

def _rows_to_raw_week_totals(rows_with_games, rcol_prefix):
    raw = {}
    for c in COUNTING_COLS:
        raw[c] = float((rows_with_games[f"{rcol_prefix}{c}"] * rows_with_games["_games"]).sum())
    fga = rows_with_games[f"{rcol_prefix}FGA_pg"] * rows_with_games["_games"]
    fta = rows_with_games[f"{rcol_prefix}FTA_pg"] * rows_with_games["_games"]
    fgm = rows_with_games[f"{rcol_prefix}FG%"] * fga
    ftm = rows_with_games[f"{rcol_prefix}FT%"] * fta
    raw["FGA"] = float(fga.sum()); raw["FGM"] = float(fgm.sum())
    raw["FTA"] = float(fta.sum()); raw["FTM"] = float(ftm.sum())
    return raw

def _team_week_raw_totals(pool, roster_names, week, weekly_games_df, rcol_prefix):
    if week not in weekly_games_df.index:
        raise ValueError(f"week {week} not found in weekly_games_df (have weeks "
                          f"{list(weekly_games_df.index)})")
    rows = pool[pool["Player"].isin(roster_names)].copy()
    if rows.empty:
        return {c: 0.0 for c in COUNTING_COLS + ["FGA", "FGM", "FTA", "FTM"]}
    week_row = weekly_games_df.loc[week]
    league_avg_games = week_row.mean()
    games = rows["Team"].map(week_row.to_dict()).fillna(league_avg_games)
    rows = rows.assign(_games=games.values)
    return _rows_to_raw_week_totals(rows, rcol_prefix)

def _add_raw(a, b):
    keys = set(a) | set(b)
    return {k: a.get(k, 0.0) + b.get(k, 0.0) for k in keys}

def _finalize_week_totals(raw):
    totals = {c: raw.get(c, 0.0) for c in COUNTING_COLS}
    fga, fta = raw.get("FGA", 0.0), raw.get("FTA", 0.0)
    totals["FG%"] = (raw.get("FGM", 0.0) / fga) if fga > 0 else np.nan
    totals["FT%"] = (raw.get("FTM", 0.0) / fta) if fta > 0 else np.nan
    return totals

