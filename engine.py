def set_draft_mode(tracker, mode):
    mode = (mode or "").strip().lower()
    if mode not in ("snake", "3rr"):
        print(f"  [!] Unknown mode '{mode}' -- use 'snake' or '3rr'.")
        return
    new_reversal_round = 3 if mode == "3rr" else 0
    if tracker.reversal_round == new_reversal_round:
        print(f"  Draft mode is already {mode.upper()}.")
        return
    new_full = _build_full_pick_order(tracker.teams, tracker.rounds, new_reversal_round)
    cutover = tracker.overall - 1  # picks already logged are untouched
    tracker.pick_order = tracker.pick_order[:cutover] + new_full[cutover:]
    tracker.reversal_round = new_reversal_round
    print(f"  Draft mode set to {mode.upper()} from pick #{tracker.overall} onward "
          f"(picks 1-{cutover} already logged are unaffected).")


def _v31_auto_recommend(self):
    """Replaces the base no-op-ish auto-recommend: prints the FULL
    feature table (via print_top3_table), not just Player/ADP/reasoning."""
    if not self.auto_recommend_teams:
        return
    if self.overall > len(self.pick_order):
        return
    on_the_clock = self.pick_order[self.overall - 1]
    if on_the_clock not in self.auto_recommend_teams:
        return
    try:
        top3, note = recommend_top3(self, team=on_the_clock, weekly_games_df=self.weekly_games_df)
    except Exception as e:
        print(f"\n[auto-recommend] Skipped for {team_label(on_the_clock)} (pick #{self.overall}): {e}")
        return
    print(f"\n>>> AUTO-RECOMMEND -- it's {team_label(on_the_clock)}'s turn "
          f"(overall #{self.overall}, round {self.current_round}) <<<")
    print_top3_table(top3, note, tracker=self, team=on_the_clock)


